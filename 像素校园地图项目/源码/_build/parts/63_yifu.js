    px(g, XW(wx), YW(wy), 1, HH(YF_WIN_H), "rgba(0,0,0,0.30)");   /* 洞口左内侧 */
    px(g, XW(wx) + 2, YW(wy) + 2, WW(YF_WIN_W) - 4, 4, YF_WIN_L);       /* 玻璃上反光 */
    px(g, XW(wx) + 2, YW(wy + YF_WIN_H) - 5, WW(YF_WIN_W) - 4, 4, shade(YF_WIN_L, -0.46));
    px(g, XW(wx) - 1, YW(wy + YF_WIN_H), WW(YF_WIN_W) + 2, 2, shade(YF_RED, 0.32));  /* 窗台 */
    px(g, XW(wx) - 1, YW(wy + YF_WIN_H) + 2, WW(YF_WIN_W) + 2, 1, "rgba(10,12,18,0.28)");
