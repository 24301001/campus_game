function dormLibRestyle(b, name) {
  const g = b.canvas.getContext("2d");
  const baseY = b.ay, bw = b.w;                   // ⚠️ b.ay 就是 30 段的 baseY；b.w 已是缩过的宽
  const x0 = 26, x1 = x0 + bw;                    // 墙的左 / 右边缘（canvas 坐标）
  const eaveY = baseY - DL_FLOORS * FLOOR_H;      // 消去 roofT：eaveY = baseY − wallH
  const wh = baseY - eaveY;                       // 墙带高（= 68）
  const PADT = 18, roofT = eaveY - PADT;          // 屋面那一段：30 段是 PADT + roofT = eaveY

  /* --- 0. 撤屋名牌（§九.4）------------------------------------------------------ */
  const sgn = makeSign(name);
  if (sgn) {
    const sg = signRect(sgn, x0, bw, eaveY);
    const px0 = sg.x - 2, py0 = sg.y - 2, pw = sg.w + 7, ph = sg.h + 7;
    g.clearRect(px0, py0, pw, ph);
    px(g, px0, py0, pw, ph, shade(DL_ROOF, -0.04));            // = 30 段屋面"板面"那一层
    for (let j = 1; j <= 3; j++) {                             // 补回被擦断的分坡脊线
      const ry = PADT + Math.round((roofT - 12) * j / 4) + 6;
      if (ry >= py0 && ry < py0 + ph) px(g, px0, ry, pw, 1, "rgba(255,255,255,0.08)");
    }
    /* 斑点**按周围密度补**，不是随手给个数：30 段那两遍是
       `(w/3)` 个白点 + `(w/4)` 个黑点铺在 `w−8 × roofT−12` 上 ⇒ 白 0.68% / 黑 0.51%。
       补丁约 63×35 ⇒ 白 15 / 黑 11。给少了那块屋顶会**比周围干净**（实测
       第一版白 6 / 黑 5 ⇒ 深色点只有 5 个 vs 左右对照组 10 个，虽在 1× 下看不出来，
       但那是一块肉眼可辨的"平滑矩形"的种子）。build.py 有断言钉住这两个数。 */
    speckle(g, px0, py0, pw, ph, "rgba(255,255,255,0.05)", 15, makeRng(6618));
    speckle(g, px0, py0, pw, ph, "rgba(0,0,0,0.07)", 11, makeRng(6619));
  }

  /* --- 1. 复算 30 段 §3.5 的窗列（逐字同一套公式 + 补 x0，见文件头 §四.3） --- */
  const margin = 22;
  const cols = Math.max(1, Math.floor((bw - margin * 2 + WIN_GAP) / (DL_WIN_W + WIN_GAP)));
  const stepX = (bw - margin * 2 - cols * DL_WIN_W) / (cols - 1 || 1);
  const colX = cn => x0 + Math.round(margin + cn * (DL_WIN_W + stepX));

  /* --- 2. 先擦掉墙左缘之外那条旧窗渣 -------------------------------------------
     30 段的窗列公式**没加 x0** ⇒ 最左一列窗画在列 21（`wx − 1`），而墙左缘是
     x0 = 26 ⇒ 墙外挂着一窄条旧窗框。重铺墙是从 x0 起的，**擦不到它**。
     只擦**左侧**：右侧旧窗（最后一列 wx+WIN_W+2 = 328）全在墙内；而右侧 padding
     里有 30 段的落地投影（shadowQuad 右移 SHX），跟着一起擦会削掉楼角影子。
     擦完由第 3 步把 30 段那几根 1px 描边补回来。 */
  g.clearRect(0, eaveY + 1, x0, wh - 1);

  /* --- 3. 重铺整条墙带：白方块瓷砖（不透明，直接盖掉旧墙/旧窗） ---------------- */
  px(g, x0, eaveY + 2, bw, wh - 2, DL_TILE);
  /* 逐块微色差：**每格都取一次 rng**，格子数与位置无关地推进（换楼不改序列） */
  const rr = makeRng(6611);
  for (let ty = eaveY + 2; ty < baseY; ty += DL_TILE_P) {
    for (let tx = x0; tx < x1; tx += DL_TILE_P) {
      const k = rr();
      const tw = Math.min(DL_TILE_P, x1 - tx), th = Math.min(DL_TILE_P, baseY - ty);
      if (k < 0.10) px(g, tx, ty, tw, th, shade(DL_TILE, -0.05));
      else if (k > 0.92) px(g, tx, ty, tw, th, shade(DL_TILE, 0.04));
    }
  }
  for (let ty = eaveY + 2 + DL_TILE_P; ty < baseY; ty += DL_TILE_P)      // 横缝
    px(g, x0, ty, bw, 1, DL_JOINT);
  for (let tx = x0 + DL_TILE_P; tx < x1; tx += DL_TILE_P)                // 竖缝
    px(g, tx, eaveY + 2, 1, wh - 2, DL_JOINT);
  /* 左右棱（照 30 段 §3.3 的受光/背光）+ 整栋外轮廓（照 §3.8） */
  px(g, x0, eaveY + 2, 3, wh - 2, shade(DL_TILE, 0.16));
  px(g, x1 - 4, eaveY + 2, 4, wh - 2, shade(DL_TILE, -0.26));
  px(g, x0 - 1, eaveY + 1, bw + 2, 1, shade(DL_TILE, -0.44));
  px(g, x0 - 1, eaveY + 1, 1, wh + 2, shade(DL_TILE, -0.44));
  px(g, x1, eaveY + 1, 1, wh + 2, shade(DL_TILE, -0.44));

  /* --- 4. 逐层的：棕带（上）→ 窗 → 棕带（下） --------------------------------- */
  const winTop = 7;                               // 窗顶相对层顶（yf）的行号
  const BAND_L = shade(DL_BAND, 0.26), BAND_D = shade(DL_BAND, -0.30);
  const winAt = (wx, wy) => {
    px(g, wx, wy, DL_WIN_W, DL_WIN_H, DL_DARK);                       // 洞口
    px(g, wx + 1, wy + 1, DL_WIN_W - 2, DL_WIN_H - 2, DL_GLASS);      // 玻璃
    px(g, wx + 2, wy + 2, DL_WIN_W - 10, 3, shade(DL_GLASS, 0.30));   // 左上高光
    px(g, wx + 1, wy + DL_WIN_H - 5, DL_WIN_W - 2, 4, shade(DL_GLASS, -0.26)); // 下段背光
    px(g, wx, wy, DL_WIN_W, 1, DL_FRAME);                             // 白框（四边）
    px(g, wx, wy + DL_WIN_H - 1, DL_WIN_W, 1, DL_FRAME);
    px(g, wx, wy, 1, DL_WIN_H, DL_FRAME);
    px(g, wx + DL_WIN_W - 1, wy, 1, DL_WIN_H, DL_FRAME);
    /* 中间白色十字（用户点名）：竖 2px + 横 2px，正落在洞口中点 */
    const cx = wx + ((DL_WIN_W / 2) | 0) - 1, cyy = wy + ((DL_WIN_H / 2) | 0) - 1;
    px(g, cx, wy, 2, DL_WIN_H, DL_FRAME);
    px(g, wx, cyy, DL_WIN_W, 2, DL_FRAME);
    px(g, cx + 2, wy, 1, DL_WIN_H, "rgba(20,26,36,0.16)");            // 棂影
    px(g, wx, cyy + 2, DL_WIN_W, 1, "rgba(20,26,36,0.16)");
  };
  const cageAt = (wx, wy) => {                    // 首层防盗窗（栅栏罩在玻璃外面）
    for (const bx of [wx + 2, wx + 5, wx + 10, wx + 13]) {
      px(g, bx, wy + 1, 1, DL_WIN_H - 2, DL_CAGE);
      px(g, bx + 1, wy + 1, 1, DL_WIN_H - 2, DL_CAGE_D);
    }
    for (const by of [wy + 5, wy + 14]) {
      px(g, wx + 1, by, DL_WIN_W - 2, 1, DL_CAGE);
      px(g, wx + 1, by + 1, DL_WIN_W - 2, 1, DL_CAGE_D);
    }
  };
  for (let f = 0; f < DL_FLOORS; f++) {
    const yf = eaveY + f * FLOOR_H;
    for (const band of DL_BANDS) {
      px(g, x0, yf + band[0], bw, band.length, DL_BAND);
      px(g, x0, yf + band[0], bw, 1, BAND_L);                         // 带顶受光
      px(g, x0, yf + band[band.length - 1], bw, 1, BAND_D);           // 带底背光
    }
    for (let cn = 0; cn < cols; cn++) {                               // 全宽铺满：中间无门（§九.3）
      const wx = colX(cn), wy = yf + winTop;
      winAt(wx, wy);
      if (f === DL_FLOORS - 1) cageAt(wx, wy);                        // 只有首层有防盗窗
    }
  }
  /* 檐下阴影（只最上一层，4 行渐隐）—— 画在棕带之后，压住带顶与瓷砖 */
  for (let i = 0; i < 4; i++)
    px(g, x0, eaveY + 2 + i, bw, 1, "rgba(14,18,28," + (0.26 * (1 - i / 4.2)).toFixed(3) + ")");

  /* --- 5. 雨水管（照 30 段 §3.6，画在窗之后 ⇒ 压在最右一列窗的右边） --- */
  const pipeX = x1 - 7;
  px(g, pipeX, eaveY + 3, 3, wh - 3, shade(DL_TILE, -0.24));
  px(g, pipeX, eaveY + 3, 1, wh - 3, shade(DL_TILE, 0.04));
  px(g, pipeX - 1, Math.round((eaveY + baseY) / 2) - 5, 5, 2, shade("#8b8f96", -0.10));
  px(g, pipeX - 1, baseY - 12, 5, 2, shade("#8b8f96", -0.22));

  contactBand(g, x0 + 1, x1 - 1, baseY - 1, 2, 0.34);                  // 接地带（与 30 段同序）

  /* --- 6. 空调外机：逐窗外挂（局部种子，绝不碰共享 RNG） --- */
  const acr = makeRng(6617);
  for (let f = 0; f < DL_FLOORS; f++) {
    const yf = eaveY + f * FLOOR_H, wy = yf + winTop;
    for (let cn = 0; cn < cols; cn++) {
      const wx = colX(cn);
      const skip = acr(), side = acr(), off = acr();
      if (skip < 0.30) continue;                                       // 三成没装
      let ax = side < 0.82 ? wx + DL_WIN_W + 2 : wx - DL_AC_W - 2;     // 绝大多数挂窗右
      if (ax < x0 + 1) ax = wx + DL_WIN_W + 2;                         // 越界改挂另一侧
      else if (ax + DL_AC_W > x1 - 1) ax = wx - DL_AC_W - 2;
      const ay = wy + Math.round((DL_WIN_H - DL_AC_H) * (0.20 + off * 0.55));
      px(g, ax, ay, DL_AC_W, DL_AC_H, DL_AC);                          // 外壳
      px(g, ax, ay, DL_AC_W, 1, "#ffffff");                            // 顶面受光
      px(g, ax, ay + DL_AC_H - 1, DL_AC_W, 1, DL_AC_D);                // 底面
      px(g, ax, ay + 2, DL_AC_W - 3, 1, "rgba(20,24,32,0.20)");        // 格栅暗线
      px(g, ax + DL_AC_W - 3, ay + 2, 3, DL_AC_H - 4, DL_AC_D);        // 右侧
      px(g, ax - 1, ay + DL_AC_H, DL_AC_W + 2, 1, "rgba(14,18,28,0.22)"); // 投影
    }
  }

  return b;
}
