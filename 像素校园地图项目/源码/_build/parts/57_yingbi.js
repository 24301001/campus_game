/* ============================================================================
 * §5.7 明湖南岸影壁群 —— 带窗影壁 × 2 + 月亮门 + 假山
 *      —— 源：_build/_photo/yingbijiashan.png（用户给的实例图）
 *      位置：用户口头指定「影壁分布在 1378 这个 y 轴上」，中间的构件是门
 * ----------------------------------------------------------------------------
 * 一、这块地是怎么来的，以及为什么**不需要清场**
 *   第六轮把明湖缩小，底部 1/4 变成「明湖南岸石板路」（ARTERY cls 1，砖石铺装）。
 *   实测那块矩形（x 2738.20..3010.52 / y 1328.01..**1424**）里：
 *     · 0 件道具、0 个碰撞盒、0 棵树（树根都在矩形外）；
 *     · 只有北缘一道路缘石，南边直接接「东西主路」的沥青。
 *   ⇒ 这是一条**本来就有的空走廊**，不需要新建路、不需要清场函数。
 *   ⚠️ 南缘是 1424 不是 ARTERY 声明的 1431.62 —— cy89（y1424..1440）那一格被
 *      后声明的「东西主路」抢走了（坑："同格重叠谁后盖"）。鸭子活动域要用这个数。
 *   ⚠️ 唯一要盯的邻居：一棵 tree (2905,1485) 站在影壁群**正南**的东西主路上
 *      （树冠 y1397..1485）。与影壁本体不重叠（树冠顶在落地线之南 19px），
 *      但玩家从南面走来会隔着它 —— 出图后若确认挡视线，再照 clearDiaClearance
 *      的先例补清场，**不预设**。
 *
 * 二、尺寸与分层从哪来（全部可回溯到实例图，不是随手拍的）
 *   实例图影壁本体 988×800 = **1.235:1**，竖向剖面（按行实测）：
 *     瓦顶 0..0.30 / 墙身 0.30..0.823 / 台基 0.826..1.0  ⇒ 30% / 52% / 17.5%
 *   这里取 YB_W=68、YB_H=56（1.214:1，与实拍差 1.7%，硬边像素下的取整损失），
 *   按同一比例切成 **瓦顶 16 / 墙身 31 / 台基 9**。
 *   配色直接量化自实例图：瓦顶 #383038、脊带 #585058、暗棕墙框 #201818、
 *   粉墙 #f0e8d8、窗棂/砖雕心 #302828、台基 #909088。
 *
 * 三、用户拍板的三处（原话有歧义，都问过了）
 *   ①「扇形」= **顶部弧形扇面**：墙身仍是矩形，只有瓦顶的上沿是一条弧。
 *   ② 中间那个「门」= **月亮门（圆洞门）**，人可以穿过去。
 *   ③ 假山在**北侧**（靠湖那面），被影壁挡住、只从墙顶和两端露出来。
 *
 * 四、布局（全部由常量算出，落点一个数字都不散写）
 *   三块同高，居中于广场：带窗影壁(68) + 缝(8) + 月亮门(52) + 缝(8) + 带窗影壁(68)
 *   = 204。广场宽 272.32 ⇒ 两侧各余 34.16px，够玩家（18 宽）和鸭子从两端绕过去。
 *   ⚠️ 广场的 x/宽与湖**同源**（都是 IX(7.0104) / IX(0.6972)），所以这里
 *      直接读 WATER[0] 的 x/w —— 抄一份数字过来迟早会和 20_ground.js 漂开。
 *
 * 五、为什么影壁与假山都必须登记 WATER_AVOID（不只是 addSolid）
 *   本轮把鸭子的活动域从"湖面"扩到"湖面 ∪ 南岸石板路"（见 45_water.js §4.5.3d）。
 *   鸭子上了岸就会撞上影壁 —— 而 avoidPush()（45_water.js:219）读的正是
 *   WATER_AVOID，它是**唯一**能让鸭子"绕开影壁、从两端缺口上岸"的机制。
 *   只 addSolid 的话鸭子会径直穿墙而过（addSolid 只管玩家）。
 *   复用 56 段的 mhSolid()：名字带 mh 是因为它诞生在明湖那轮，但它做的事
 *   ——「固体盒 + 同步登记水避让盒」——正是这里要的，不另抄一份。
 * ==========================================================================*/

