const YB_BASE = "#8a867e", YB_BASE_L = "#9c988e", YB_BASE_D = "#57544e";
/* 假山配色：照实例图的**扁圆鹅卵石**取色 —— 受光米白 / 中灰侧面 / 深灰底 + 粗黑缝。
   ⚠️ 不直接用 56 段的 MH_RK_*：那套是"浅灰偏暖、比湖心岛台面亮"，摆灰砖广场上会整块跳出来。 */
const YB_JSEAM = "#26242a";                                   // 石缝 / 中央透洞（近黑）
const YB_J1 = ["#e8e1ce", "#b0aca4", "#78787c", "#f4efdf"];   // 亮石（米白）
const YB_J2 = ["#c4bcae", "#948e84", "#5e5a56", "#d4cdbe"];   // 中石
const YB_J3 = ["#8a8a90", "#5e5e64", "#3a3a40", "#9c9ca2"];   // 深灰石笋
const YB_J4 = ["#b09068", "#8a7050", "#5c4834", "#c0a078"];   // 棕石（实例图里唯一的暖色）

/* --- 5.7.2 一块影壁（或月亮门） ---
   kind: "win" = 带窗影壁 / "door" = 月亮门（圆洞）。
   画序：台基 → 墙框 → 粉墙 → **挖洞（clearRect 留透明）** → 窗棂或圆洞描边 → 弧形瓦顶。
   ⚠️ 挖洞用逐行 clearRect 而不是 arc+clip：canvas 的 arc 有抗锯齿，在硬边像素画里
      会在洞口边缘糊出一圈半透明的灰，缩放时尤其明显。逐行算 dx 是本项目一贯做法
      （同 circlePx / ellipsePx / drawSwimRing）。 */
function makeYingbi(w, kind) {
  const c = mkCanvas(w, YB_H), g = c.getContext("2d");
  const yWall = YB_ROOF_H, yBase = YB_H - YB_BASE_H;      // 16 / 47

  /* 台基：三层退台（须弥座），自下而上收。实拍是"上枋亮、束腰中、下枋暗"。
     ⚠️ 层间各补一条暗线：三档灰在 1× 下差得不多，不画分界就并成一整块。 */
  px(g, 8, yBase,     Math.max(1, w - 16), 3, YB_BASE_L); // y47..49 上枋（最窄）
  px(g, 4, yBase + 3, Math.max(1, w - 8),  3, YB_BASE);   // y50..52 束腰
  px(g, 0, yBase + 6, w,                   3, YB_BASE_D); // y53..55 下枋（最宽 = 精灵满宽）
  px(g, 4, yBase + 3, Math.max(1, w - 8),  1, "rgba(26,22,18,0.5)");  // 上枋 / 束腰分界
  px(g, 0, yBase + 6, w,                   1, "rgba(26,22,18,0.5)");  // 束腰 / 下枋分界

  /* 墙身：先铺满暗棕墙框，再把粉墙贴在框内 ⇒ 四周自然露出一圈"框"。
     粉墙 60×25（左右各让 4，上下各让 3）。 */
  px(g, 0, yWall, w, YB_H - YB_BASE_H - YB_ROOF_H, YB_FRM);
  px(g, YB_FRAME, yWall + 3, w - YB_FRAME * 2, 25, YB_WALL);
  px(g, YB_FRAME, yWall + 3 + 24, w - YB_FRAME * 2, 1, YB_WALL_D);   // 粉墙下沿背光

  if (kind === "door") {
    /* 月亮门：整圆洞，**洞底切平在台基顶**（y47），否则圆底是个尖点、人走过去像踩在针上。
       圆心 y = 47 − 10 = 37 ⇒ 圆跨 y27..47，切掉 y47 那一行。 */
    const cx = w / 2, cy = yBase - YB_DOOR_R;
    for (let i = -YB_DOOR_R; i <= YB_DOOR_R; i++) {
      const y = Math.round(cy + i);
      if (y >= yBase) continue;
      const t = YB_DOOR_R * YB_DOOR_R - i * i;
      if (t < 0) continue;          // ⚠️ 是 <0 不是 <=0：i=±R 那一行也要走，否则圆顶缺一条边
      const dx = Math.floor(Math.sqrt(t));
      g.clearRect(Math.round(cx - dx), y, dx * 2 + 1, 1);
      /* 洞口**外**缘 1px 暗线：不然圆洞与粉墙的交界在 1× 下读不出来，
         整块墙会像"缺了一角"而不是"有个门"。 */
      px(g, cx - dx - 1, y, 1, 1, YB_LATT);
      px(g, cx + dx + 1, y, 1, 1, YB_LATT);
      /* 洞口**内**缘再压 1px 半透明暗 = 门洞侧壁的厚度。只有外缘一圈线的话洞看着像贴纸；
         有了这一圈才读得出"墙有厚度、门是穿过去的"。洞净宽 20 → 内缘各吃 1px 后仍有 18。 */
      if (dx >= 3) {
        px(g, cx - dx + 1, y, 1, 1, "rgba(46,38,36,0.5)");
        px(g, cx + dx - 1, y, 1, 1, "rgba(46,38,36,0.5)");
      }
    }
  } else {
    /* 窗洞 36×15，落在粉墙（y19..43）正中 ⇒ 上下各留 5；左右各留 12（粉墙 60 宽）。
       **挖空 = 画布上留透明**：渲染序是 地面 → drawWater → 道具，透明处自然露出
       影壁背后的湖水/砖面 —— 这正是用户要的"把中间挖空作为窗户"。 */
    g.clearRect(16, 24, 36, 15);
    /* 窗棂：2 竖 1 横。不加的话挖出来的就是个洞，不像窗。不想要删这三行即可。 */
    px(g, 28, 24, 1, 15, YB_LATT);
    px(g, 40, 24, 1, 15, YB_LATT);
    px(g, 16, 31, 36, 1, YB_LATT);
    px(g, 16, 24, 36, 1, YB_FRM_L);         // 窗楣（上沿一道亮线，等于给洞口加了过梁）
    px(g, 16, 38, 36, 1, YB_FRM_L);         // 窗台
  }

  /* 平直瓦顶，四层照实例图（**无弧**）：正脊 → 筒瓦瓦垄 → 檐口 → 滴水，两端带翘角。 */
  const yTile = YB_RIDGE_H;                                  // 7：瓦垄上沿
  const hTile = YB_ROOF_H - YB_RIDGE_H - YB_EAVE_H;          // 7：瓦垄高

  /* ① 正脊：实拍是深灰紫（#43404a），不是黑。脊顶一条亮线、脊下一条暗线。
     中段脊顶**下移 2px**，把画布最上面两行让给两端的翘角 —— 画布顶到 y0，
     没有负行可用，翘角只能靠"中段下沉"腾出高度。 */
  px(g, 0, 2, w, YB_RIDGE_H - 2, YB_RIDGE);
  px(g, 0, 2, w, 1, YB_ROOF_L);
  px(g, 0, YB_RIDGE_H - 1, w, 1, YB_ROOF_D);
  /* ② 翘角：两端各 5px，比中段脊顶高 2px，向内一格格落回。照实例图的"燕尾"——
     它是影壁最显眼的特征，画弱了整块墙就变成个普通方框。 */
  for (const dir of [1, -1]) {
    const xEnd = dir > 0 ? 0 : w - 1;
    for (let i = 0; i < 5; i++) {
      const yt = i < 3 ? 0 : i - 2;                          // 0,0,0,1,2
      px(g, xEnd + dir * i, yt, 1, YB_RIDGE_H - yt, YB_RIDGE);
      px(g, xEnd + dir * i, yt, 1, 1, YB_ROOF_L);
    }
  }
  /* ③ 筒瓦瓦垄：**浅色筒瓦面 + 深色沟**（第一版画反了，整片糊成黑）。
     每 4px 一根、2px 宽的受光面，左缘再提 1px 高光 —— 这才是"读出瓦垄"的关键。 */
  px(g, 0, yTile, w, hTile, YB_ROOF);                        // 先铺满沟色
  /* 每 4px 一根：**3px 瓦面 + 1px 沟**。2px 瓦面时白黑各半，看着像栅栏不是瓦。 */
  for (let x = 1; x < w - 1; x += 4) {
    px(g, x, yTile, Math.min(3, w - 1 - x), hTile, YB_TILE);
    px(g, x, yTile, 1, hTile, YB_TILE_L);
  }
  /* ④ 檐口：一道深带，下沿按同一节拍点浅色滴水瓦。 */
  px(g, 0, YB_ROOF_H - YB_EAVE_H, w, YB_EAVE_H, YB_EAVE);
  for (let x = 1; x < w - 1; x += 4) px(g, x, YB_ROOF_H - YB_EAVE_H, 1, 1, YB_DRIP);
  px(g, 0, YB_ROOF_H, w, 1, "rgba(20,14,10,0.35)");          // 檐口投在墙身上的一道影

  return { canvas: c, ax: Math.round(w / 2), ay: YB_H, w: w, h: YB_H };
}

/* --- 5.7.3 假山 ---
   照实例图的**扁圆鹅卵石堆**：石头宽:高 ≈ 1.8:1、四角圆润，三档色
   （上 38% 受光亮面 / 中 34% 中间调 / 下 28% 暗面）+ 左上高光斑，
   石头之间靠**各自的 1px 描边**形成细黑缝（**没有整块底色**），右侧一丛深灰石笋，
   右下角一块棕石，中央一个透洞。
   ⚠️ 第一版拿 YB_JSEAM **铺满整个 50×62 当"石缝"**，于是露在影壁墙顶外面的那一块是个
      **方正的黑矩形** —— 用户 2026-09-13：「假山不要有背景色」。缝改由 jPebble 每块
      自己描边之后，精灵四角是透明的，露出来的才是石头本身的圆弧轮廓。
   ⚠️ 第一版直接复用 56 段的 mhRock 画，出来是一堆**米白纸箱** —— 它的多边形顶点全
      落在四个角上，本质是**有棱角的方石**；实例图里全是扁的、圆的。根因在形状不在配色，
      所以这里不抠 mhRock 的参数，改用 jPebble() 逐行算半宽画椭圆。
   ⚠️ mhRock 上一轮为本段加的第 7 参 cols 现在没调用点了，但**留着**：它是纯加法
      （不传 = 逐字节原样），删它要动 56 段并触发 build.py 那两条断言，收益为零。 */

/* 一块扁圆鹅卵石。逐行算半宽画硬边椭圆 —— 不用 arc：arc 有抗锯齿，在硬边像素画里
   会在石缘糊出一圈半透明灰（同 5.7.2 挖门洞的取舍）。
   cp = [受光亮面, 中间调, 暗面, 高光] */
function jPebble(g, x, y, w, h, cp) {
  const cx = (w - 1) / 2, cy = (h - 1) / 2;
  for (let iy = 0; iy < h; iy++) {
    const dy = (iy - cy) / (cy + 0.5);
    const t = 1 - dy * dy;
    if (t <= 0) continue;
    const dx = Math.sqrt(t) * (cx + 0.5);
    const x0 = Math.round(cx - dx);
    const cw = Math.round(cx + dx) - x0 + 1;
    const f = iy / h;
    /* ⚠️ 每块石头自带 1px 深色描边（= 石缝）。删掉整块矩形底之后，缝只能这么来：
       后画的石头把自己的边压在先画的石头上，缝宽恒为 1px，而且假山的**外轮廓**
       是石头自己的椭圆弧、不是一个方框 —— 用户 2026-09-13：「假山不要有背景色」。 */
    px(g, x + x0 - 1, y + iy, cw + 2, 1, YB_JSEAM);
    px(g, x + x0, y + iy, cw, 1, f < 0.38 ? cp[0] : (f < 0.72 ? cp[1] : cp[2]));
  }
  /* 左上高光斑：没有它每块石头都是"平"的，整座山糊成一片 */
  px(g, x + Math.round(w * 0.20), y + Math.round(h * 0.18),
     Math.max(1, Math.round(w * 0.28)), 1, cp[3]);
  /* 右下压暗（光自左上 ⇒ 右下背光） */
  px(g, x + Math.round(w * 0.62), y + Math.round(h * 0.80),
     Math.max(1, Math.round(w * 0.30)), 1, cp[2]);
}

function makeJiashan() {
  const c = mkCanvas(YB_JIASHAN_W, YB_JIASHAN_H), g = c.getContext("2d");
  /* ⚠️ 这里**不许**铺矩形底色（第一版就是 `px(g, 0, 0, W, H, YB_JSEAM)`）。画布留透明，
     石缝由每块石头自己的 1px 描边拼出来 —— 见 jPebble 与 §5.7.3 文件头。 */
  /* [x, y, w, h, 配色] —— y 升序 = 从最远（上）那块开始画，下面的压住上面的底边 */
  /* ⚠️ 纵向步进必须**小于石高 3px 左右**：椭圆四角是缩进的（15×10 的椭圆四角各缩 ~2px），
     按石高排会露出 4px 的黑缝，整座山变成"悬浮的一摞盘子"；实例图的缝其实只有 1px 上下。
     所以石头是**互相压着**排，不是挨着排。 */
  const B = [
    [19,  0, 14, 10, YB_J1], [ 6,  2, 12,  9, YB_J2],                    // 顶
    [12,  7, 25, 11, YB_J1], [31,  9, 13, 10, YB_J1],                    // 上
    [17, 15, 20, 10, YB_J1], [ 1, 16, 17, 11, YB_J1], [35, 19, 12, 10, YB_J2],  // 中
    [ 7, 23, 25, 12, YB_J1], [29, 29, 16, 10, YB_J1],                    // 中下
    [ 0, 32, 19, 12, YB_J1], [17, 35, 23, 11, YB_J1], [35, 38, 13, 10, YB_J2],  // 底
    [ 4, 44, 20, 11, YB_J2], [23, 46, 22, 10, YB_J1], [10, 52, 24, 10, YB_J1]   // 底脚
  ];
  for (const b of B) jPebble(g, b[0], b[1], b[2], b[3], b[4]);
  /* 中央透洞：太湖石的"透"。⚠️ 不许画成一块方正的黑 —— 那看着像"挖了个洞"，
     不像石头透光。三块不等大的暗凑出个不规则形状才对。 */
  px(g, 21, 28, 6, 4, YB_JSEAM);
  px(g, 19, 31, 9, 5, YB_JSEAM);
  px(g, 23, 35, 5, 5, YB_JSEAM);
  /* 右侧一丛深灰石笋（实例图右缘那簇）：没有它整座山是一团浅色，缺个"锚" */
  jPebble(g, 38, 20,  8, 28, YB_J3);
  jPebble(g, 43, 33,  6, 15, YB_J3);
  /* 右下角一块棕石（实例图里唯一的暖色，压住右下角） */
  jPebble(g, 36, 47, 11, 12, YB_J4);
  /* ⚠️ 原来这里有一条 x2..47 横贯的"山脚接地暗带" —— 删了。它横跨整个画布宽，而画布
     已经没有底色，最底那块石头（x10..33）根本盖不住它，会在半空多出一条悬空的暗杠。
     接地的活儿交给石头自己的"下 28% 暗面"：假山只从墙顶露出 10px 一个头，山脚永远在
     影壁背后、看不见，本来也不需要。 */

  return { canvas: c, ax: Math.round(YB_JIASHAN_W / 2), ay: YB_JIASHAN_H,
           w: YB_JIASHAN_W, h: YB_JIASHAN_H };
}

/* --- 5.7.4 摆场 --- */
function buildYingbi() {
  /* 广场 x 范围与湖**同源** —— 都是 IX(7.0104) / IX(0.6972)（见文件头四）。
     这里直接读 WATER[0]，不抄数字。 */
  const X0 = WATER[0].x, PW = WATER[0].w, CX = X0 + PW / 2;
  const SPAN = YB_W * 2 + YB_DOOR_W + YB_GAP * 2;              // 204
  const HALF = SPAN / 2;                                       // 102
  const cw = CX - HALF + YB_W / 2;                             // 西影壁中心 = CX − 68
  const cd = CX;                                               // 月亮门中心
  const ce = CX + HALF - YB_W / 2;                             // 东影壁中心 = CX + 68

  for (const cx of [cw, ce]) {
    addProp(Object.assign({}, makeYingbi(YB_W, "win"), { x: cx, y: YB_BY, tag: "yingbi" }));
    mhSolid(cx, YB_BY, YB_W, YB_SOLID_D);
  }

  /* 月亮门：**两个**盒子夹出中间 20 宽的门洞 —— 门洞那一段不加盒，人和鸭子才能穿。
     ⚠️ 门洞的通行判据不是"视觉上的洞"，而是"这里没有 solids"：demo 的 blocked()
        和这里的 ptBlocked() 都是遍历 solids 的 AABB，看不见精灵长什么样。 */
  const jamb = (YB_DOOR_W - YB_DOOR_HOLE) / 2;                 // 16
  addProp(Object.assign({}, makeYingbi(YB_DOOR_W, "door"), { x: cd, y: YB_BY, tag: "yingbi" }));
  mhSolid(cd - (YB_DOOR_W / 2 - jamb / 2), YB_BY, jamb, YB_SOLID_D);   // 西侧门垛 = cd − 18
  mhSolid(cd + (YB_DOOR_W / 2 - jamb / 2), YB_BY, jamb, YB_SOLID_D);   // 东侧门垛 = cd + 18

  /* 假山：西影壁**背后**（北侧），略偏西 4px。YB_JIASHAN_DY = 4 ⇒ 墙顶只冒 10px 一个头
     （用户 2026-09-13：「往前移动一点假山，能够露出个头在墙后即可」）。 */
  const jx = cw - 4, jby = YB_BY - YB_JIASHAN_DY;
  addProp(Object.assign({}, makeJiashan(), { x: jx, y: jby, tag: "jiashan" }));
  mhSolid(jx, jby, YB_JIASHAN_W, YB_JIASHAN_D);
}
