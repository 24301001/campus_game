/* --- 5.14.3 几何：宽锚现算，一处写死 ---------------------------------------- */
function jxGeo(c) {
  const wallH0 = JX_FLOORS * FLOOR_H;
  const roofT  = c.height - JX_PADT - wallH0 - JX_PADB;   // 反解，不存第二份
  const eaveY  = JX_PADT + roofT;                         // 檐下沿 = 墙顶
  const w      = c.width - JX_PADX * 2;                   // 立面外框宽 = footprint 宽
  const sc     = w / JX_EW;                               // 每英寸多少世界像素
  const U      = (v) => Math.round(v * sc);
  const FH     = U(JX_EH);                                // 立面高 = 114
  const y0     = eaveY;                                   // 立面第 0 行（外框顶）
  const G = {
    roofT: roofT, wallH: wallH0, eaveY: eaveY, y0: y0,
    x0: JX_PADX, x1: JX_PADX + w, w: w, sc: sc, U: U,
    FH: FH, baseY: y0 + FH, H: y0 + FH + JX_PADB,
    /* 英寸 → 画布；矩形一律**两端各取整再相减**（不许把宽单独取整 ——
       相邻两块会因此差 1px 露缝，见 30 段的教训）。 */
    rect: (o) => [JX_PADX + Math.round(o.x * sc), y0 + Math.round(o.y * sc),
                  Math.round((o.x + o.w) * sc) - Math.round(o.x * sc),
                  Math.round((o.y + o.h) * sc) - Math.round(o.y * sc)]
  };
  /* 几何闸：30 段的 PADT/画布高公式一动，反解出来的 roofT 立刻出界 ——
     出图时是一栋比例崩掉的楼，而三套自动验收都不看画面。 */
  if (roofT < 20 || roofT > 190)
    console.warn("65_jixie: 反解出的 roofT=%d 出了 30 段的 clamp 区间[20,190]，" +
                 "画布高 %d 与 PADT/wallH/SHY 公式对不上了", roofT, c.height);
  /* 字体闸：点阵字高必须 ≈ 楼名带高的 JX_GLYPH_R —— 换字体、改带高，
     这一条会先响，而不是等出图才发现字太大太小。 */
  const gh = JX_CHARS[0][2];
  let tw = JX_GAP * (JX_CHARS.length - 1);
  for (const e of JX_CHARS) tw += e[1];
  const bandH = U(JX_BAND.h), bandW = U(JX_BAND.w);
  if (Math.abs(gh - Math.round(bandH * JX_GLYPH_R)) > 1 || tw > bandW * 0.5)
    console.warn("65_jixie: 点阵 %d 行 / 总宽 %d 与楼名带 %d×%d 行对不上" +
                 "（字高应 ≈%d 行、总宽应 < %d）—— 重跑 _build/_jxfont.py？",
                 gh, tw, bandW, bandH, Math.round(bandH * JX_GLYPH_R), bandW >> 1);
  return G;
}

/* --- 5.14.4 楼名带五字：逐点 1bit 掩膜 + 平涂墨 --------------------------------
   与 `_build/_jxfont.py` 的 brush() **逐条同构**（probe 图就是按这支笔出的，
   观感判据才有效）：`L` 是"上方为空"的那一列（金底黑字下与 M 同值，留档是为了
   换成用户口径的「金字」时不用改这里）。 */
function jxGlyph(g, b64, nw, nh, x, y) {
  const s = atob(b64), bit = (i) => (s.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
  for (let j = 0; j < nh; j++) {
    for (let i = 0; i < nw; i++) {
      if (!bit(j * nw + i)) continue;
      const up = (j === 0) || !bit((j - 1) * nw + i);
      px(g, x + i, y + j, 1, 1, up ? JX_INK.L : JX_INK.M);
      if (j + 1 < nh && !bit((j + 1) * nw + i)) px(g, x + i, y + j + 1, 1, 1, JX_INK.D);
    }
  }
}

/* 五字在楼名带里**居中**排布（正面图里也是居中的：墨迹中心 527.4pt、
   带中心 527.7pt，差 0.3pt ⇒ 就是居中，不是左对齐）。 */
function jxPlaque(g, r) {
  let tw = JX_GAP * (JX_CHARS.length - 1);
  for (const e of JX_CHARS) tw += e[1];
  const gh = JX_CHARS[0][2];
  let x = r[0] + ((r[2] - tw) >> 1);
  const y = r[1] + Math.max(0, (r[3] - gh) >> 1);
  for (const e of JX_CHARS) {
    jxGlyph(g, e[0], e[1], e[2], x, y);
    x += e[1] + JX_GAP;
  }
}

/* --- 5.14.5 逐块落地：四条边规则 ---------------------------------------------
   ppt 的描边一律不画（见文件头坑 ③），改按 SUN（左上受光）给每条边定档：
     · `b` 楼体 / `t` 附楼坡顶 / `w` 门廊白框 / `c` 柱梁 / `n` 楼名带
       —— **凸出的实体**：上+左提亮、下+右压暗；
     · `g` 玻璃 / `d` 门 —— **凹进去的口**：上沿压暗、下沿提亮（正好反相）。
       这一条是"玻璃在柱子后边"读起来像玻璃的关键：柱子是凸的、玻璃是凹的，
       两套边一正一反，6px 宽的柱身才立得起来。
   ⚠️ 白柱的 `COL_L` 与底色同值（纯白提亮无处可提）—— 只画下/右那条暗边，
      这正合正面图：柱子就是纯白一块，靠压在橙墙上的轮廓分开。
   ⚠️ 太小的块（宽 < 4 或高 < 6）**不描边** —— 6px 见方的附楼小窗描完边只剩中间
      一格，比不描还糊。 */
const JX_K_LIT = { b: 1, c: 1, w: 1, n: 1, t: 1 };
const JX_K_BASE = { b: JX_C.BODY, c: JX_C.COL, g: JX_C.GLASS, n: JX_C.BAND,
                    d: JX_C.DOOR, w: JX_C.WHITE, t: JX_C.BODY };
const JX_K_L = { b: JX_C.BODY_L, c: JX_C.COL_L, w: JX_C.WHITE_L, n: JX_C.BAND_L };
const JX_K_D = { b: JX_C.BODY_D, c: JX_C.COL_D, w: JX_C.WHITE_D, n: JX_C.BAND_D };

function jxBlk(g, r, k, rng) {
  const x = r[0], y = r[1], w = r[2], h = r[3];
  if (w <= 0 || h <= 0) return;
  if (k === "t") {                                   // 附楼坡屋顶：顶点在上的等腰三角
    const ax = x + (w >> 1), ay = y, bx = x + w - 1, by = y + h - 1;
    poly(g, [[ax, ay], [bx, by], [x, by]], JX_C.BODY);
    for (let j = 0; j < h; j++) {                    // 左坡受光、右坡背光
      const t = j / Math.max(1, h - 1);
      px(g, Math.round(ax + (x - ax) * t), y + j, 1, 1, JX_C.BODY_L);
      px(g, Math.round(ax + (bx - ax) * t), y + j, 1, 1, JX_C.BODY_D);
    }
    px(g, x, by, w, 1, JX_C.BODY_D);
    return;
  }
  px(g, x, y, w, h, JX_K_BASE[k]);
  /* 楼体的墙面颗粒：只用**局部** rng —— 碰共享流会重掷全校园散射（60 段 §6.6 那颗地雷） */
  if (k === "b" && w >= 10 && h >= 10) {
    speckle(g, x + 1, y + 1, w - 2, h - 2, "rgba(255,255,255,0.05)", (w * h / 90) | 0, rng);
    speckle(g, x + 1, y + 1, w - 2, h - 2, "rgba(0,0,0,0.06)", (w * h / 130) | 0, rng);
  }
  if (w < 4 || h < 6) return;
  if (JX_K_LIT[k]) {
    px(g, x, y, w, 1, JX_K_L[k]);
    px(g, x, y, 1, h, JX_K_L[k]);
    px(g, x, y + h - 1, w, 1, JX_K_D[k]);
    px(g, x + w - 1, y, 1, h, JX_K_D[k]);
  } else {                                           // 玻璃 / 门：凹口，反相
    px(g, x, y, w, 1, JX_C.GLASS_D);
    px(g, x, y + h - 1, w, 1, JX_C.GLASS_L);
  }
}

