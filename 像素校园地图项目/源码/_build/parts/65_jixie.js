function jxPiers(G) {
  const ps = [];
  for (const e of JX_EL) if (e[0] === "c") ps.push(e);
  ps.sort(function (a, b) { return a[1] - b[1]; });
  const keep = [];
  if (ps.length >= 4) {                              // 少于 4 根就不猜，原样返回
    const gaps = [];
    for (let i = 1; i < ps.length; i++) gaps.push(ps[i][1] - (ps[i - 1][1] + ps[i - 1][3]));
    const med = gaps.slice().sort(function (a, b) { return a - b; })[gaps.length >> 1];
    for (let i = 0; i < ps.length; i++) {
      const gl = i > 0 ? gaps[i - 1] : Infinity;
      const gr = i + 1 < ps.length ? gaps[i] : Infinity;
      if (gl < med * 0.5 && gr < med * 0.5) continue;   // 被两边挤住 = 手误柱，整根不画
      keep.push(ps[i]);
    }
  } else keep.push.apply(keep, ps);
  const w = keep[0][3], x0 = keep[0][1];
  const last = keep[keep.length - 1], x1 = last[1] + last[3];
  const ppx = Math.round((x1 - x0 - w) * G.sc / (keep.length - 1));   // ④ 整像素间距
  const out = [];
  for (let i = 0; i < keep.length; i++)
    out.push({ x: x0 + i * ppx / G.sc, y: keep[i][2], w: w, h: keep[i][4], src: keep[i] });
  return out;
}

/* 表里每个 `c` → 正则化后的柱（或 null = 这根是手误柱、整根不画）。 */
function jxPierMap(G) {
  const m = new Map();
  for (const e of JX_EL) if (e[0] === "c") m.set(e, null);
  for (const p of jxPiers(G)) m.set(p.src, p);
  return m;
}

