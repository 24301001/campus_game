/* =========================================================
   0. 常量 / 标尺
   ---------------------------------------------------------
   标尺由**思源楼**推出（用户给定：思源楼 = 50 米）：

     思源楼世界宽  450 px = 50 m   ⇒ 1 世界像素 ≈ 0.1111 m
     思源楼 PPT 宽 1.1521 in       ⇒ 1 英寸 = 450 / 1.1521 = 390.5911 px

   世界尺寸 = 整张 PPT 幻灯片（13.33333 × 7.5 英寸）。
   三重交叉验证见交接文档 §4.4（篮球场 28.7m / 网球场 25.0m）。
   ========================================================= */
const TILE    = 32;                           // 瓦片尺寸（保持颗粒感）
const U       = 450 / 1.1521;                 // 390.5911 世界像素 / 英寸
const IX      = v => v * U;                   // 英寸 → 世界像素
const WORLD_W = Math.round(13.33333 * U);     // 5208
const WORLD_H = Math.round(7.5 * U);          // 2929（7.5×390.5911=2929.43）
const VIEW_W  = 480, VIEW_H = 270;            // **背板**尺寸（16:9），整数倍放大到屏幕
                                              // ⚠️ 它不等于可见世界尺寸：世界视口 = 背板 / zoom
const BASE_SPEED = 200;                       // 1× 档下的行走速度（世界像素/秒）

/* --- 缩放 ---------------------------------------------------------
   zoom = 每个世界像素占几个背板像素。背板恒为 VIEW_W×VIEW_H 不变，
   所以 zoom=4 就是"把 120×67 的世界区域放大 4 倍显示" —— 像素风里这就是变大看细节，
   信息量本来就在背板里，不需要动背板分辨率。
   于是：可见世界尺寸 = VIEW_W/zoom × VIEW_H/zoom。

   档位刻意**离散**：像素风连续缩放只会糊。且 ≥1 的档位只取整数 ——
   非整数倍最近邻放大必然出现"某列 1px、某列 2px"的宽窄不齐。

   两端都由用户定死：一端是"整个校园"（FIT，再往外就是世界外的纹理区，没意义），
   另一端封顶 3×（视野 ≈18×10 米）—— 再拉近就只看得见一个门洞，容易"不知道自己站在哪"。 */
const FIT = Math.min(VIEW_W / WORLD_W, VIEW_H / WORLD_H);   // ≈0.09217：整幅铺满视口
const ZOOM_STEPS = [FIT, 1 / 8, 1 / 6, 1 / 4, 1 / 3, 1 / 2, 1, 2, 3];
let zoomI = ZOOM_STEPS.indexOf(1);            // 默认 1×（与无缩放版观感完全一致）
let zoom  = ZOOM_STEPS[zoomI];
let viewW = VIEW_W / zoom, viewH = VIEW_H / zoom;   // 可见世界矩形尺寸
const mips = [];                              // 地面 mip 金字塔（÷1 ÷2 ÷4 ÷8），6.0.1 填

/* PPT 形状 {x,y,w,h}（英寸）→ 世界像素矩形 */
const rc = s => ({ x: IX(s.x), y: IX(s.y), w: IX(s.w), h: IX(s.h) });

