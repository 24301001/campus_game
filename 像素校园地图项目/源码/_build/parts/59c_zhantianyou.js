/* ============================================================================
 * §5.21 詹天佑雕塑 —— 思源楼前雕塑区西侧铺装走道（用户指定世界坐标 1818, 1927）
 *      —— 源：预览/zhaitianyoudiaoxiang.png
 * ----------------------------------------------------------------------------
 * 一、用户口径（逐字）
 *   「继续看雕塑图片，詹天佑雕塑应该放到1818 1927那里，给我完整复刻出来」
 *
 * 二、照片读出来的六条（1152 × 1920，已排除右下角"豆包AI生成"水印）
 *   量测脚本：_build/_zwm2.py（本文所有数字都是它的输出，不是目测）
 *     ① **站立像**：面朝正南（本项目所有人物一律朝南），双臂自然垂在身侧，
 *        **右手（观众看来的左侧）屈肘搭在腰腹前**、左手垂得更低；
 *     ② **深棕长外套**，敞开，露内里的**马甲 + 白衬衫领 + 深色领带**；
 *        大衣裳长及胯，下摆比躯干略宽（照片 330px / 245px = 1.35）；
 *     ③ **浓密的八字胡**——这是詹天佑最好认的那个特征，在 34px 尺度下
 *        正好占满脸宽的那一整行，必须画；
 *     ④ **深色长裤 + 皮鞋**，裤宽（200px）**比躯干（245px）窄**，
 *        所以本件**不套用**伟人像那条"下身与上身同宽"的口径（见 §三）；
 *     ⑤ 站在一根**暗红花岗岩圆柱**上，圆柱**上细下粗**（柱头 250/303 →
 *        柱身 330），柱身中段正面嵌一块**金色铭牌**；
 *     ⑥ 柱下是**三层逐级放大的圆形底盘**（365 / 416 / 484→530）。
 *
 * 三、⚠️ 与 59b 伟人像**口径不同**的两处（不是疏漏，是照片不一样）
 *   ① 伟人像第二轮用户明确要求「下身裤子和上身宽度要求一致」；本件的**照片里
 *      裤 200px 明显窄于躯干 245px**，照伟人那条画会与照片不符 ⇒ **取照片**。
 *   ② 伟人像有**一圈石头栏杆**，本件**没有**——照片里只有柱子与底盘，
 *      直接坐在铺装上。⇒ 不画栏杆、不做围栏碰撞盒。
 *
 * 四、⚠️ 本件推进 solids ⇒ 又一次重掷全校园散射（同 §六地雷）
 *   `addSolid(ZT_CX, ZT_S, ZT_SOL_W, ZT_SOL_D)` 是本轮**第三处**推进 solids 的
 *   地方（前两处：§6.5g 网球场、§6.5h 伟人像栏杆）。
 *   solids 一变 `ptBlocked` 的判定就变，散射循环里既当"已接受点数"又当
 *   **物种种子**（`anyTree((n*131+11)|0)`）的那个 `n` 平移 ⇒ 全校园的树 /
 *   灌木 / 花坛 / 垃圾桶重掷一遍（60 段 §6.6 头部那条地雷，
 *   [[pixel-campus-scatter-seed-landmine]]）。
 *   accept / verify / zoomtest 三套**一个数都不会变**；唯一探针是
 *   `_build/_propdiff.py`（必须跳过 `tag==='duck'`）。
 *   ⚠️ 本件的盒子落在**铺装走道**上（实测走道带 y ≈ 1883..1976），盒子
 *      y ∈ [1920, 1933] 整段在走道内 —— 走道上本就没有散射点，
 *      所以**预计 `_propdiff` 会全绿**。但"预计"不是"证据"，仍旧按地雷处理：
 *      跑完 `_propdiff` 才算数（[[feedback-no-speculative-tooling]]）。
 *
 * 五、几何一律从**用户坐标**派生，不存第二份
 *   `ZT_CX / ZT_CY` 是用户给的那两个数，其余（底盘三层、柱身、柱头、精灵画布框、
 *   锚点、碰撞盒、净空框、铭牌位置）全部由它们现算 —— 铁律「派生量不许再存
 *   一份常量」（56_minghu.js 踩过：湖一缩小，贴着湖的旧坐标全废）。
 *
 * 六、⚠️ 已知的画不出来的东西（**必须向用户报告，不许含糊**）
 *   金色铭牌上的「詹天佑」三个字**在本尺度下无法辨认**：铭牌只有 10px 宽，
 *   三字各分到 ≈3px，再扣边框就剩 2px —— 写什么都是三个黑点。
 *   ⇒ 本件画**三个 1×2 的暗色字位点**示意"牌上有字"，**不试图写真字**。
 *     这是尺度决定的，不是没做（对照：天佑会堂的匾额 70b 有 18px 字号可用）。
 * ==========================================================================*/

const ZT_CX = 1818, ZT_CY = 1927;      // ← 用户指定的世界坐标（**最底盘底椭圆的中心**）

/* --- 5.11.1 圆柱：底盘三层 + 柱身 + 柱头（世界像素）---
   ⚠️ 屏幕映射是 (x, y, z) → (x, y − z)，所以"高"占屏幕的**竖直**那一段、
      "半径"占**水平**那一段 —— 与伟人像底座顶面/立面那段注释同一条口径。
   ⚠️ 半径（rx）一律取**偶数对齐的整数**、且左右对称：本项目全程硬边，
      px() 走 fillRect，半像素立刻糊出抗锯齿边（59b 踩过）。
   ⚠️ 椭圆投影比 1.71:1（53 段文件头实测值），ry = round(rx / 1.71)。 */
const ZT_B1_RX = 11, ZT_B1_RY = 6, ZT_B1_H = 2;   // 底盘第 1 层（最下、最宽）
const ZT_B2_RX =  9, ZT_B2_RY = 5, ZT_B2_H = 2;   // 底盘第 2 层
const ZT_B3_RX =  8, ZT_B3_RY = 5, ZT_B3_H = 2;   // 底盘第 3 层
const ZT_SH_RX =  7, ZT_SH_RY = 4, ZT_SH_H = 24;  // 柱身
const ZT_CP_RX =  6, ZT_CP_RY = 4, ZT_CP_H = 2;   // 柱头（比柱身**收** 1px ⇒ 照片里柱子上细下粗）

/* 三层底盘的底心（自下而上），全部由 ZT_CY 现算 */
const ZT_B1_YB = ZT_CY;                            // 1927 ← 精灵落地基准（最南沿 = YB + RY）
const ZT_B2_YB = ZT_B1_YB - ZT_B1_H;               // 1925
const ZT_B3_YB = ZT_B2_YB - ZT_B2_H;               // 1923
const ZT_SH_YB = ZT_B3_YB - ZT_B3_H;               // 1921 柱身底心
const ZT_SH_YT = ZT_SH_YB - ZT_SH_H;               // 1897 柱身顶心
const ZT_CP_YB = ZT_SH_YT;                         // 1897 柱头底心
const ZT_CP_YT = ZT_CP_YB - ZT_CP_H;               // 1894 柱头顶面（= 人的落脚基准）

/* 最南沿：第 1 层底椭圆的南极点。addProp 的 y / addSolid 的 by 都用它。 */
const ZT_S  = ZT_B1_YB + ZT_B1_RY;                 // 1933
/* 最南的**画出来**的点也是它（底盘 1 的底椭圆），所以落地线与画布基准同一处。 */

/* --- 5.11.2 人：34 高，站在**柱头顶面**上（不是柱身顶）---
   ⚠️ 脚取顶面椭圆**中心往南 2px**（`ZT_CP_YT + 2`）而不是正中：轴测里"站在台面
      正中"会读成"悬在台口上方"，往南压一点才像踩实了 —— 与伟人像 `WR_PED_YF − 7`
      同一个经验（那边 7/16 ≈ 44%，这边 2/5 ≈ 40%，同一比例）。
   ⚠️ 34 = 照片 824px × (34/824)。分段比例逐段照照片换算，不是拍脑袋：
      头 5 / 颈 1 / 躯干 21 / 裤 5 / 鞋 2。 */
const ZT_FIG_H = 34;
const ZT_FOOT  = ZT_CP_YT + 2;                     // 1896 脚底（站在柱头顶面里）
const ZT_FIG_T = ZT_FOOT - ZT_FIG_H;               // 1862 头顶

/* --- 5.11.3 铭牌：柱身中段正面 ---
   照片：铭牌 y 1314..1446（柱身 1076..1670 的 40%..64% 处），x 444..678。
   本件取"柱身上半段正中"，10 宽 × 6 高（照片 235×132 按同一比例缩）。 */
const ZT_PLQ_W = 10, ZT_PLQ_H = 6;
const ZT_PLQ_X0 = ZT_CX - ZT_PLQ_W / 2;            // 1813
const ZT_PLQ_Y0 = ZT_SH_YT + 6;                    // 1903（柱身顶往下 6）

/* --- 5.11.4 调色 ---
   人取**青铜**（照片是被包浆压暗的深铜，不是石头的灰）；柱子取**暗红花岗岩**，
   比人**冷**一档、也暗一档 —— 两者同色会糊成一坨（53 段齿轮环与铁砧分开一档
   亮度的同一条经验）。铭牌是整件唯一的高明度色，照片里它是唯一抓眼的东西。 */
const ZT_CU_L = "#ab9280", ZT_CU_M = "#8a7364", ZT_CU_D = "#5f4e43";   // 铜（脸/手）
const ZT_CO_L = "#8a7261", ZT_CO_M = "#655245", ZT_CO_D = "#443830";   // 大衣
const ZT_VEST = "#4a3e36", ZT_SHIRT = "#cdc5b6", ZT_TIE = "#2b2420";   // 马甲/衬衫/领带
const ZT_PANT = "#4a3d36", ZT_SHOE = "#2a2422", ZT_HAIR = "#2a2320";   // 裤/鞋/发须
const ZT_GR_L = "#8a736a", ZT_GR_M = "#6d5952", ZT_GR_D = "#4c3b35";   // 花岗岩受光/侧/暗
const ZT_GR_T = "#96827a";                                            // 花岗岩顶面
const ZT_GOLD = "#f2d78e", ZT_GOLD_L = "#fff2c0", ZT_GOLD_D = "#a8894a"; // 铭牌

/* ============================================================================
 * 5.11.5 椭圆工具（逐行扫描线，硬边、无抗锯齿）
 *   ⚠️ **不引用 53 段的 ellipPx** —— 那两个函数（ellipPx / ellipRing）是为
 *      齿轮环写的，本件只需要"实心椭圆"这一个能力，自带一份比跨文件耦合更省事：
 *      53 段哪天把 ellipPx 改名/改签名，本件不会跟着碎。
 *   ⚠️ 每行都过 Math.max(1, ...)：rx 衰减到 0 的那一两行若不兜底，
 *      会画出零宽 fillRect（静默无事）或负宽（Chrome 直接忽略），都不报错但缺像素。
 * ==========================================================================*/
function ztEllip(g, cx, cy, rx, ry, col) {
  if (!(rx > 0) || !(ry > 0)) return;
  const X = Math.round(cx), Y = Math.round(cy);
  for (let y = Math.ceil(Y - ry); y <= Math.floor(Y + ry); y++) {
    const s = 1 - ((y - Y) / ry) ** 2;
    if (s <= 0) continue;
    const hw = rx * Math.sqrt(s), x0 = Math.round(X - hw);
    px(g, x0, y, Math.max(1, Math.round(X + hw) - x0), 1, col);
  }
}

/* 一段圆柱（直筒，不是锥台）：底心 (cx, yB)、半轴 (rx, ry)、高 h。
   屏幕上的三步 = ① 底圈（下半弧露在矩形外）② 柱身矩形 ③ 顶面椭圆。
   ⚠️ 次序不能换：顶面必须**最后**画，否则柱身矩形会把它盖掉；
      底圈必须**最先**画，否则它会被柱身矩形齐刷刷切掉下半。
   ⚠️ "上细下粗"不靠锥台插值实现，靠**叠三层半径递减的直筒** ——
      三层之间的台阶正好读成线脚（照片里柱子本来就是分段的）。 */
function ztDrum(g, cx, yB, rx, ry, h, cTop, cSide, cDark) {
  const yT = yB - h;
  ztEllip(g, cx, yB, rx, ry, cDark);                       // ① 底圈
  px(g, cx - rx, yT, rx * 2, h, cSide);                    // ② 柱身
  px(g, cx - rx, yT, 1, h, shade(cSide, 0.18));            //    西棱受光（SUN 在西北）
  px(g, cx + rx - 1, yT, 1, h, shade(cSide, -0.22));       //    东棱背光
  ztEllip(g, cx, yT, rx, ry, cTop);                        // ③ 顶面
}

/* ============================================================================
 * 5.11.6 柱座（三层底盘 → 柱身 → 柱头）
 * ==========================================================================*/
function ztPedestal(g) {
  ztDrum(g, ZT_CX, ZT_B1_YB, ZT_B1_RX, ZT_B1_RY, ZT_B1_H, ZT_GR_T, ZT_GR_M, ZT_GR_D);
  ztDrum(g, ZT_CX, ZT_B2_YB, ZT_B2_RX, ZT_B2_RY, ZT_B2_H, ZT_GR_T, ZT_GR_M, ZT_GR_D);
  ztDrum(g, ZT_CX, ZT_B3_YB, ZT_B3_RX, ZT_B3_RY, ZT_B3_H, ZT_GR_T, ZT_GR_M, ZT_GR_D);
  ztDrum(g, ZT_CX, ZT_SH_YB, ZT_SH_RX, ZT_SH_RY, ZT_SH_H, ZT_GR_T, ZT_GR_M, ZT_GR_D);
  ztDrum(g, ZT_CX, ZT_CP_YB, ZT_CP_RX, ZT_CP_RY, ZT_CP_H, ZT_GR_T, ZT_GR_M, ZT_GR_D);
}

/* 金色铭牌（柱身中段正面）+ 三个字位点。见文件头 §六：字**认不出来**，只示意。 */
function ztPlaque(g) {
  const x0 = ZT_PLQ_X0, y0 = ZT_PLQ_Y0, w = ZT_PLQ_W, h = ZT_PLQ_H;
  px(g, x0 - 1, y0 - 1, w + 2, h + 2, shade(ZT_GR_D, -0.24));   // 暗底衬（把牌从柱面上切出来）
  px(g, x0, y0, w, h, ZT_GOLD);
  px(g, x0, y0, w, 1, ZT_GOLD_L);                               // 上棱受光
  px(g, x0, y0 + h - 1, w, 1, ZT_GOLD_D);                       // 下棱背光
  px(g, x0, y0, 1, h, ZT_GOLD_L);
  px(g, x0 + w - 1, y0, 1, h, ZT_GOLD_D);
  for (let i = 0; i < 3; i++)                                   // 三个字位点（10/3 ≈ 3px 一格）
    px(g, x0 + 2 + i * 3, y0 + 2, 1, 2, ZT_GOLD_D);
}

/* ============================================================================
 * 5.11.7 人（站立像，双臂垂在身侧，右手屈肘搭在腰腹前）
 *   自上而下：头 5（含发 2）/ 颈 1 / 躯干 21 / 裤 5 / 鞋 2 = 34。
 *   ⚠️ 人物一律面朝南 ⇒ **右手 = 屏幕左侧**，与 59b 伟人像同一条口径，别画反。
 * ==========================================================================*/
function ztFigure(g) {
  const cx = ZT_CX, foot = ZT_FOOT, T = ZT_FIG_T;
  const faceB = T + 5, neckB = T + 6;        // 下颌 / 肩线
  const hemB  = T + 27;                      // 大衣下摆
  const pantB = foot - 2;                    // 裤脚（鞋上沿）

  /* ① 头：发 2 + 脸 3，**不加鬓发** —— 照片里头宽/头高 = 103/131 = 0.79，
        4 宽 × 5 高正好 0.80 ✓；两侧各加 1px 鬓发会把比例顶到 1.2，脑袋立刻变方
        （第一版即如此）。这里的背景是深棕柱子，深色短发本来就切得出来。 */
  px(g, cx - 2, T, 4, 2, ZT_HAIR);
  px(g, cx - 2, T + 2, 4, 3, ZT_CU_L);
  px(g, cx - 2, T + 2, 1, 1, shade(ZT_CU_L, -0.34));          // 左眼
  px(g, cx + 1, T + 2, 1, 1, shade(ZT_CU_L, -0.34));          // 右眼
  /* ⭐ 八字胡：**占满脸宽的那一整行**。这是詹天佑最好认的特征，
     34px 尺度下别的都可以省，这一行不能省（见文件头 §二③）。 */
  px(g, cx - 2, T + 3, 4, 1, ZT_HAIR);
  px(g, cx - 1, T + 4, 2, 1, shade(ZT_CU_M, -0.10));          // 下巴影

  /* ② 颈（1px —— 再薄就没了，再厚就顶掉一格躯干） */
  px(g, cx - 1, faceB, 2, 1, shade(ZT_CU_M, -0.12));

  /* ③ 躯干：大衣 8 宽（cx−4..cx+4），中间 4 宽敞开露马甲 */
  const tb = neckB, tbH = hemB - tb;
  px(g, cx - 4, tb, 8, tbH, ZT_CO_M);
  px(g, cx - 4, tb, 1, tbH, ZT_CO_L);                         // 西侧受光
  px(g, cx + 3, tb, 1, tbH, ZT_CO_D);                         // 东侧背光
  /* 敞开处：白衬衫领（顶 2 行）→ 领带 → 马甲 */
  px(g, cx - 2, tb, 4, tbH - 2, ZT_VEST);
  px(g, cx - 2, tb, 2, 2, ZT_SHIRT);
  px(g, cx, tb, 2, 2, ZT_SHIRT);
  px(g, cx - 1, tb + 2, 2, 6, ZT_TIE);
  for (let y = tb + 4; y < hemB - 3; y += 4) px(g, cx - 1, y, 1, 1, shade(ZT_VEST, -0.34));
  /* 大衣翻领：V 形两块（比大衣亮一档，才读得出"翻"） */
  px(g, cx - 4, tb, 2, 3, shade(ZT_CO_M, 0.22));
  px(g, cx + 2, tb, 2, 3, shade(ZT_CO_M, 0.22));
  /* ④ 下摆：比躯干外挑 1px/侧（照片 330/245 = 1.35，本件 10/8 = 1.25） */
  px(g, cx - 5, hemB - 6, 10, 6, ZT_CO_M);
  px(g, cx - 5, hemB - 6, 1, 6, shade(ZT_CO_M, 0.16));
  px(g, cx + 4, hemB - 6, 1, 6, shade(ZT_CO_M, -0.20));
  px(g, cx - 5, hemB - 1, 10, 1, shade(ZT_CO_M, -0.16));      // 下摆压暗

  /* ⑤ 裤：8 宽（**与躯干同宽**，照片 200/245 ≈ 0.8 —— 本件 8/8=1.0 略宽，
        是硬边项目"再窄就只剩 6px、两条腿并成一根"的下限，见文件头 §三①） */
  px(g, cx - 4, hemB, 8, pantB - hemB, ZT_PANT);
  px(g, cx - 4, hemB, 1, pantB - hemB, shade(ZT_PANT, 0.16));
  px(g, cx + 3, hemB, 1, pantB - hemB, shade(ZT_PANT, -0.20));
  px(g, cx, hemB, 1, pantB - hemB, shade(ZT_PANT, -0.12));    // 裤缝（明暗线，不是缝隙）
  /* 鞋 */
  px(g, cx - 4, pantB, 8, foot - pantB, ZT_SHOE);
  px(g, cx - 4, pantB, 8, 1, shade(ZT_SHOE, 0.28));
  px(g, cx, pantB, 1, foot - pantB, shade(ZT_SHOE, -0.34));

  /* ⑥ 右臂（**屏幕左侧**）垂到肘后屈向腹前。照片：手在**胸口下方**（y425 ⇒ T+10）。
        ⚠️ 两条手臂**不能同色** —— 屏幕左侧是受光面（SUN 在西北），右臂取大衣的
          亮档、左臂取暗档；同色的话 12px 宽的身子会读成一根直筒（第一版即如此）。
        ⚠️ 高度照照片：右手 T+10、左手 T+14 ⇒ **右高左低**，别画成对称。 */
  px(g, cx - 6, tb + 1, 2, 6, ZT_CO_L);                       // 上臂（垂下）T+7..T+13
  px(g, cx - 6, tb + 1, 1, 6, shade(ZT_CO_L, 0.14));
  px(g, cx - 5, tb + 4, 4, 2, ZT_CO_L);                       // 前臂（往内收）T+10..T+12
  px(g, cx - 5, tb + 4, 4, 1, shade(ZT_CO_L, 0.16));
  px(g, cx - 1, tb + 4, 2, 2, ZT_CU_L);                       // 手（铜 · 亮档）
  px(g, cx - 1, tb + 4, 2, 1, shade(ZT_CU_L, 0.18));
  /* ⑦ 左臂（屏幕右侧）垂得更低（照片 y505 ⇒ T+14） */
  px(g, cx + 4, tb + 1, 2, 7, ZT_CO_M);
  px(g, cx + 4, tb + 1, 1, 7, shade(ZT_CO_M, -0.10));
  px(g, cx + 5, tb + 1, 1, 7, ZT_CO_D);
  px(g, cx + 4, tb + 8, 2, 2, ZT_CU_M);                       // 手（铜 · 中档）T+14..T+16

  /* ⑧ 站在柱头顶面上的接地：脚下一道深带（不是投影 —— 投影落在顶面上会读成"悬空"） */
  contactBand(g, cx - 4, cx + 4, foot - 1, 2, 0.22);
}

/* ============================================================================
 * 5.11.8 几何自检（构建时跑一次，只 warn 不抛 —— 与本项目其余段同款）
 *   ⚠️ canvas 越界是**静默**的：多画 1px 就被裁掉一条边还不报错。所以这些
 *      判据必须"照着画布框与画出来的东西"核对，不能只看尺寸表自洽。
 * ==========================================================================*/
function ztAudit() {
  /* ⚠️ 每一条都写成**独立的 console.warn 字面量**（而不是抽一个 bad() 助手）：
     build.py 的几何闸是按 `console.warn(` 的出现次数数的 —— 抽成助手的话
     八条自检只算一处，闸门就形同虚设（70b 段同样写法，同一条理由）。 */
  if (!(ZT_CP_YT < ZT_CP_YB))
    console.warn("[§5.21 詹天佑] 柱头没有高度");
  if (!(ZT_FOOT <= ZT_CP_YT + ZT_CP_RY))
    console.warn("[§5.21 詹天佑] 脚底不在柱头顶面椭圆内（会读成悬空）");
  if (!(ZT_FIG_T > ZT_CV_Y0))
    console.warn("[§5.21 詹天佑] 头顶出画布北沿（会被静默裁掉）");
  if (!(ZT_S < ZT_CV_Y1))
    console.warn("[§5.21 詹天佑] 底盘南沿出画布南沿（投影没地方了）");
  if (!(ZT_CX - ZT_B1_RX > ZT_CV_X0))
    console.warn("[§5.21 詹天佑] 底盘西沿出画布西沿");
  if (!(ZT_CX + ZT_B1_RX + Math.round(-SUN.x * 26) <= ZT_CV_X1))
    console.warn("[§5.21 詹天佑] 底盘东沿 + 方向性投影出画布东沿");
  if (!(ZT_PLQ_Y0 > ZT_SH_YT && ZT_PLQ_Y0 + ZT_PLQ_H < ZT_SH_YB))
    console.warn("[§5.21 詹天佑] 铭牌不在柱身范围内（会压到柱头或柱脚上）");
  if (!(ZT_B1_RX > ZT_SH_RX && ZT_SH_RX > ZT_CP_RX))
    console.warn("[§5.21 詹天佑] 底盘/柱身/柱头半径次序反了（照片里是上细下粗，单调收分）");
}

/* ============================================================================
 * 5.11.9 雕塑精灵
 *   ⚠️ 画布框**一律从上面那些尺寸派生**，不各写一个绝对数字 ——
 *      整个组件再挪再长，框自己跟上（59b 第一版正是"一排手量的整数"出的血）。
 *        西 = 底盘 1 西沿再往外 4
 *        东 = 底盘 1 东沿 + 方向性投影 SHX + 4
 *        北 = 头顶再往上 8
 *        南 = 落地线 + 26（方向性投影 SHY=21 + 余量）
 *   ⚠️ SHX / SHY 是**函数内现算**的局部量，**不是**全局常量（59b 踩过：
 *      顶层直接写 SHX ⇒ 加载期 ReferenceError，整页 JS 死、而三套自动验收全绿）。
 * ==========================================================================*/
const ZT_CV_X0 = ZT_CX - ZT_B1_RX - 4;                 // 1803
const ZT_CV_X1 = ZT_CX + ZT_B1_RX + 20;                // 1849（含 SHX=16）
const ZT_CV_Y0 = ZT_FIG_T - 8;                         // 1854
const ZT_CV_Y1 = ZT_S + 26;                            // 1959（含 SHY=21）
const ZT_CV_W = ZT_CV_X1 - ZT_CV_X0;                   // 46
const ZT_CV_H = ZT_CV_Y1 - ZT_CV_Y0;                   // 105

function ztStand() {
  const c = mkCanvas(ZT_CV_W, ZT_CV_H), g = c.getContext("2d");
  /* ⚠️ 用 canvas 变换把画布原点挪到世界 (ZT_CV_X0, ZT_CV_Y0)，于是下面每个绘图
     函数都直接吃**世界坐标**（等价于 53 段到处包一层的 diaX/diaY，只是少写几百个
     括号）。能这么干的前提：px / shadowQuad / contactBand 全都只走 fillRect 路径
     —— 已核实（_build/_syn.js:180-195）；ztEllip 是本件自己的，也是纯 fillRect。
     哪天有工具改成 getImageData / 或读 g.canvas 的像素，这条就失效。 */
  g.translate(-ZT_CV_X0, -ZT_CV_Y0);
  const SHX = Math.round(-SUN.x * 26), SHY = Math.round(-SUN.y * 26);

  /* ① 地面投影（SUN 在西北 ⇒ 影子朝右下）。先接地影椭圆（贴柱脚一圈），
        再方向性拖影 —— 两笔合起来才读得出"这柱子压在地上"。 */
  ztEllip(g, ZT_CX + 1, ZT_B1_YB + 2, ZT_B1_RX + 1, ZT_B1_RY + 1, "rgba(14,18,28,0.22)");
  shadowQuad(g, ZT_CX - ZT_B1_RX + 3, ZT_B1_YB - 8, ZT_CX + ZT_B1_RX - 3, ZT_B1_YB + 4,
             SHX, SHY, 0.24, 4);

  ztPedestal(g);
  ztPlaque(g);
  ztFigure(g);

  ztAudit();
  /* ⚠️ 锚点是**画布坐标**（不受 translate 影响，addProp 认的就是这个）*/
  return { canvas: c, ax: ZT_CX - ZT_CV_X0, ay: ZT_S - ZT_CV_Y0 };
}

/* ============================================================================
 * 5.21.10 碰撞盒：**只封柱座**，不封人
 *   用户口径里没有栏杆，所以盒子就是柱座那圈。宽取底盘 1 的直径（22）、
 *   进深取"南沿往回 13"（盖住底盘三层的全部可见占地 + 一点点余量）。
 *   ⚠️ 与 59b 不同：那边盒子 = 整个栏杆圈（把玩家挡在圈外）；这边玩家可以
 *      贴着柱子走，只是**进不去柱子**。
 * ==========================================================================*/
const ZT_SOL_W = ZT_B1_RX * 2;                         // 22
const ZT_SOL_D = 13;

/* ============================================================================
 * 5.21.11 净空：把柱座周围的散落道具清掉（树 / 灌木 / 路灯）
 *   净空框 = **精灵画布框（ZT_CV_*）本身，不往外扩** —— 判据对的是"画出来的东西"
 *   （画布框），不是"柱子多大"这个间接量。
 *   ⚠️ 与 §5.10.9 的 ±8 不同，这里**故意不留余量**，理由是实测出来的：
 *      画布框南沿 = ZT_S + 26 = 1959，而正南恰好有一棵树
 *      （signature `tree,1844,2091,46,132`，它树顶的屏幕 y = 2091 − 132 = 1959），
 *      **正好相切**。外扩 8 会把"美术盒 ∩ 净空框 = 6px"判成冲突 ⇒ 凭空删掉一棵
 *      离柱座 164px、树冠比柱座落地线还低 26px 的树（`_propdiff` 实录：
 *      ONLY-OLD 就是它）。画布框已经把投影余量（南 +26 / 东 +20）算进去了，
 *      所以"不压进框"= "不压到任何一画"，再加余量只会误伤。
 *   ⚠️ 必须排在 §6.6c 的 clearPropTreeClash() **之后**（先跑会改它的保留集，
 *      clashDropped 的计数跟着变，验收数字就对不上了 —— 同 §5.10.9 的约束）。
 * ==========================================================================*/
const ZT_CLR = { x: ZT_CV_X0, y: ZT_CV_Y0, w: ZT_CV_W, h: ZT_CV_H };
function clearZtClearance() {
  const C = ZT_CLR, cx1 = C.x + C.w, cy1 = C.y + C.h;
  const keep = [];
  let dropped = 0;
  for (const p of props) {
    /* 雕塑自己保留；宽 > 110 的当楼处理（同 §5.10.9 —— 小道具最大 ≈86px，楼最小 ≈150px） */
    if (p.tag === "zhantianyou" || p.img.width > 110) { keep.push(p); continue; }
    const x0 = p.x - p.ax, y0 = p.y - p.ay;
    if (x0 < cx1 && x0 + p.img.width > C.x && y0 < cy1 && y0 + p.img.height > C.y) {
      dropped++;
      continue;
    }
    keep.push(p);
  }
  props.length = 0;
  for (const p of keep) props.push(p);
  return dropped;
}
