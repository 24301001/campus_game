/* --- 5.18.3 几何：宽锚现算，一处写死 ---------------------------------------- */
function wjGeo(c) {
  /* ⚠️ 顺序要紧：`depth` 必须**先**从 30 段给的画布高推出来，`roofT` 再跟着它走。
     60 段给本楼开了 `roofFull` ⇒ 30 段画布高 = `PADT + ceil(进深) + PADB`
     （那个式子里**没有墙高** —— 这正是第三十二轮能删掉 `WJ_BASE_MUL` 的原因）。 */
  const depth  = c.height - WJ_PADT - WJ_PADB;             // = ceil(进深) = 528
  const wallH0 = WJ_WALL_MUL * FLOOR_H;                    // 102 = 3 × 34（与七教每层齐平）
  const roofT  = depth - wallH0;                           // 426 —— 与两栋体育馆同一条规矩：
                                                           //   屋带 + 墙高 = 进深
                                                           // ⇒ 精灵的实体部分**恰好铺满
                                                           //   自己的 footprint**，北缘
                                                           //   不会露出灰石板
                                                           // ⚠️ 这个数**只影响"坡有多长"**
                                                           //   了，不再影响屋顶"看起来多高"
                                                           //   （那个由 `WJ_GABLE` 单独管）
  const eaveY  = WJ_PADT + roofT;                          // 檐下沿 = 立面顶 = 444
  const baseY  = eaveY + wallH0;                           // 落地线 = 546（= 30 段的 ay，没挪）
  const H      = baseY + WJ_PADB;                          // 自算画布高 = 581（= 30 段的画布高）
  const w      = c.width - WJ_PADX * 2;                    // 立面外框宽 = footprint 宽 = 214
  const sc     = w / WJ_PW;                                // 照片 px → 精灵列（横向）
  const sv     = wallH0 / WJ_RISE;                         // 照片 px → 精灵行（纵向）
  /* 照片 x → 画布列（**两端各取整再相减**：相邻两块才不会差 1px 露缝，30 段的教训） */
  const X = (v) => WJ_PADX + Math.round((v - WJ_PX0) * sc);
  /* 照片 y → 画布行（锚在"屋面压墙顶"那一行上；照片 y 越小越靠上 ⇒ 行越小） */
  const Y = (v) => eaveY + Math.round((v - WJ_GY0) * sv);
  const cx = WJ_PADX + w / 2;                              // 立面中轴 = 133
  const G = {
    roofT: roofT, wallH: wallH0, eaveY: eaveY, baseY: baseY,
    x0: WJ_PADX, x1: WJ_PADX + w, w: w, sc: sc, sv: sv, X: X, Y: Y, cx: cx,
    H: H
  };
  const box = (a, b, top, bot) => ({ x0: X(a), x1: X(b) - 1, top: top, bot: bot });
  /* 竖带 —— **只存一套、只有一个方向**，其余（砖带 / 窗行）全部现算。
     ⚠️ 这是第 54 条那个坑的正面防法：两张方向相反的表必然炸（68 段栽过）。 */
  G.under  = { top: eaveY, bot: Y(WJ_COPE_Y[0]) - 1 };       // 檐下暗带（照片 583..598，实测 #25282d）
  G.cope   = { top: Y(WJ_COPE_Y[0]), bot: Y(WJ_COPE_Y[1]) }; // 檐口带（灰）
  G.copeb  = G.cope.bot + 1;                                 // 檐口下缘那道近黑红边（实测 #23060a）
  G.brickT = G.cope.bot + 2;                                 // 砖墙顶行（照片 ~633）
  G.plin   = { top: Y(WJ_PLIN_Y[0]), bot: Y(WJ_PLIN_Y[1]) }; // 墙裙
  G.gnd    = { top: G.plin.bot + 1, bot: baseY - 1 };        // 墙脚外那道**浅**散水（实测 #d8d0ce）
  G.band   = [];
  for (let i = 0; i < 2; i++)                                // 两条层间灰带
    G.band.push({ top: Y(WJ_BAND_Y[i * 2]), bot: Y(WJ_BAND_Y[i * 2 + 1]) });
  /* 三排窗：**只存"窗顶行"一件事**，窗底 = 顶 + WJ_WIN_H − 1（结构上不可能反过来） */
  G.winRow = WJ_WIN_Y.map(Y);
  /* 横向：窗只存中心，宽度统一（三扇一样宽 —— 照片量出 13.5/14.6/13.7，取 14） */
  G.corner = [[X(WJ_CORNER[0]), X(WJ_CORNER[1]) - 1], [X(WJ_CORNER[2]), X(WJ_CORNER[3]) - 1]];
  G.pil2   = [[X(WJ_PIL2[0]), X(WJ_PIL2[1]) - 1], [X(WJ_PIL2[2]), X(WJ_PIL2[3]) - 1]];
  G.winC   = WJ_WINC.slice();
  G.door   = box(WJ_DOOR_X[0], WJ_DOOR_X[1], Y(WJ_DOOR_Y[0]), Y(WJ_DOOR_Y[1]));
  /* 砖壁柱：左一根照相片，右一根镜像（关于立面中轴） */
  const rl = X(WJ_RELIEF_X), rr = X(WJ_RELIEF_X + WJ_RELIEF_W) - 1;
  G.relief = [[rl, rr], [Math.round(2 * cx - 1 - rr), Math.round(2 * cx - 1 - rl)]];
  G.pipes  = WJ_PIPE_X.map(X);
  /* 屋面：檐口出挑 4 行（照片 24 px × sc = 4.2）；正脊走**中轴竖线**（南北向，见文件头） */
  G.ov     = 4;
  G.ex0    = G.x0 - G.ov; G.ex1 = G.x1 + G.ov;
  G.cxr    = (G.ex0 + G.ex1) / 2;
  G.cxi    = Math.round(G.cxr);                // 正脊所在**列**（南北向 ⇒ 脊线是竖的）
  G.gable  = WJ_GABLE;                         // 山墙三角的行高
  G.ridgeY = eaveY - G.gable;                  // 山墙尖（= 正脊南端）所在**行**

  /* --- 闸（写在页面里，任何自动验收都读不到 —— 只有出图看得见，第 55 条）--- */
  if (c.height !== WJ_PADT + depth + WJ_PADB)
    console.warn("69_wujiao: 30 段画布高 %d ≠ PADT + 进深 %d + PADB = %d —— 画布高公式变了",
                 c.height, depth, WJ_PADT + depth + WJ_PADB);
  /* ⭐ 跨表的对账闸（第三十二轮新增，替代原来那条"roofT 反解"）：把从**画布高**反解出的
     进深与 `20_ground.js` 的 CAMPUS 对一遍。两条错法都能被它抓住：
       ① 60 段那一行漏了给本楼开 `roofFull` ⇒ 30 段的画布高变成
          `PADT + round(0.6·进深) + 墙高 + PADB`，反解出来的数**偏小一大截**；
       ② CAMPUS 的 `h` 被改了而这里没跟着动。 */
  const _row = CAMPUS.find((e) => e[0] === WJ_NAME);
  if (!_row) console.warn("69_wujiao: CAMPUS 里找不到「%s」—— 名字被改过了？", WJ_NAME);
  else if (Math.abs(depth - Math.ceil(IX(_row[5]))) > 1)
    console.warn("69_wujiao: 从画布高反解出的进深 %d 与 CAMPUS 的 ceil(IX(h)) = %d 对不上" +
                 "（差 %d）—— 多半是 60 段没给本楼开 roofFull，或 CAMPUS 那一行刚改过",
                 depth, Math.ceil(IX(_row[5])), Math.abs(depth - Math.ceil(IX(_row[5]))));
  if (H !== WJ_PADT + roofT + wallH0 + WJ_PADB)
    console.warn("69_wujiao: 自算画布高 %d ≠ PADT+roofT+wallH+PADB = %d ⇒ 楼会被裁掉或底下留空",
                 H, WJ_PADT + roofT + wallH0 + WJ_PADB);
  if (roofT + wallH0 < depth)
    console.warn("69_wujiao: 屋带 %d + 墙高 %d = %d < 进深 %d ⇒ 精灵盖不满 footprint，" +
                 "北缘会露出一条灰石板（`paintCells` 给 K.BLD 铺的楼前硬地）",
                 roofT, wallH0, roofT + wallH0, depth);
  if (wallH0 !== WJ_WALL_MUL * FLOOR_H)
    console.warn("69_wujiao: 墙高 %d ≠ WJ_WALL_MUL(%d) × FLOOR_H(%d)",
                 wallH0, WJ_WALL_MUL, FLOOR_H);
  if (G.gable * 3 > roofT)
    console.warn("69_wujiao: 山墙高 %d 吃掉屋带 %d 的三分之一以上 ⇒ 屋带只剩两个小坡，" +
                 "南北向正脊的「长」就读不出来了", G.gable, roofT);
  if (G.cxi !== Math.round(cx))
    console.warn("69_wujiao: 正脊列 %d ≠ 立面中轴 %d —— 脊没走在轴上", G.cxi, Math.round(cx));
  if (G.ridgeY <= WJ_PADT || G.ridgeY >= eaveY)
    console.warn("69_wujiao: 山墙尖第 %d 行跑到屋带 [%d,%d] 外面了", G.ridgeY, WJ_PADT, eaveY);
  const stack = [G.under.top, G.under.bot, G.cope.top, G.cope.bot, G.brickT,
                 G.plin.top, G.plin.bot, G.gnd.top, G.gnd.bot];
  for (let i = 1; i < stack.length; i++)
    if (stack[i] < stack[i - 1])
      console.warn("69_wujiao: 立面竖带第 %d 项(%d) 跑到上一项(%d) 上面了 —— %s",
                   i, stack[i], stack[i - 1], stack.join(","));
  G.band.forEach((b, i) => {
    if (b.top >= b.bot) console.warn("69_wujiao: 第 %d 条层间灰带上下沿反了", i + 1);
    if (b.top <= G.brickT || b.bot >= G.plin.top)
      console.warn("69_wujiao: 第 %d 条层间灰带 %d..%d 越出砖墙 [%d,%d]",
                   i + 1, b.top, b.bot, G.brickT, G.plin.top);
  });
  if (!(G.winRow[0] < G.winRow[1] && G.winRow[1] < G.winRow[2]))
    console.warn("69_wujiao: 三排窗的行 %s 不是自上而下递增", G.winRow.join(","));
  for (let f = 0; f < 3; f++) {
    if (G.winRow[f] <= G.cope.bot)
      console.warn("69_wujiao: 第 %d 排窗顶 %d 压到檐口带上", f + 1, G.winRow[f]);
    if (G.winRow[f] + WJ_WIN_H > G.plin.top)
      console.warn("69_wujiao: 第 %d 排窗底 %d 压到墙裙 %d 上",
                   f + 1, G.winRow[f] + WJ_WIN_H, G.plin.top);
  }
  if (G.door.bot > G.baseY - 4 || G.door.top < G.cope.bot)
    console.warn("69_wujiao: 大门行 %d..%d 越出墙面 [%d,%d]",
                 G.door.top, G.door.bot, G.cope.bot, G.baseY - 4);
  if (G.door.x0 <= G.pil2[0][1] || G.door.x1 >= G.pil2[1][0])
    console.warn("69_wujiao: 大门列 %d..%d 压到两根中柱上了", G.door.x0, G.door.x1);
  if (G.winC[1] !== Math.round(cx))
    console.warn("69_wujiao: 中间那扇窗的中心 %d ≠ 立面中轴 %d —— 立面对不齐了",
                 G.winC[1], Math.round(cx));
  /* ⚠️ 占位要按**含白框(±1)与凹边(±2)**算，不是按玻璃宽算 —— 否则"没压柱子"
     是假绿。第一版就是按玻璃宽判的，框画在框外以后判据就松了。 */
  const oxw = (WJ_WIN_W - 1) >> 1;
  G.winC.forEach((c0, i) => {
    const a0 = c0 - oxw - 2, a1 = c0 + (WJ_WIN_W - 1 - oxw) + 2;
    const bad = (i === 0 && a1 >= G.pil2[0][0]) || (i === 1 && (a0 <= G.pil2[0][1] || a1 >= G.pil2[1][0]))
             || (i === 2 && a1 >= G.corner[1][0]);
    if (bad) console.warn("69_wujiao: 第 %d 扇窗 %d..%d 压到相邻的灰壁柱上", i + 1, a0, a1);
    if (a0 < 0 || a1 >= c.width) console.warn("69_wujiao: 第 %d 扇窗出了画布", i + 1);
  });
  if (G.ex0 < 0 || G.ex1 >= c.width)
    console.warn("69_wujiao: 檐口列 %d..%d 出了画布宽 %d", G.ex0, G.ex1, c.width);
  return G;
}

/* --- 5.18.4 屋面：**南北向正脊的双坡顶**（第三十三轮重做） -------------------
   屏上从上到下依次是：北端远檐边 → 两个坡面夹一条**竖直的正脊** → 南端山墙三角 → 南檐口。
   ⚠️ 全程**不取随机数**：屋面板不用 30 段那套 speckle ⇒ 建筑 RNG 序列一个数不动。
   ⚠️ 每一笔都被 `F()` 夹在 [ex0, ex1] 里、行也只在 [yTop, yBot) 里
      ⇒ 结构上不可能留缝、也不可能画到画布外面去（旧的"三段铺满"换成"两段铺满"）。 */
function wjRoof(g, G) {
  const ex0 = G.ex0, ex1 = G.ex1, yTop = WJ_PADT, yBot = G.eaveY;
  const cxi = G.cxi, YR = G.ridgeY, GA = G.gable;
  const half = (ex1 - ex0) / 2;               // 半宽（列）—— 山墙三角的底半宽
  const STEP = 7, R = Math.round;             // 瓦纹间距
  /* 瓦纹暗线：比坡面本色压暗的幅度。
     ⚠️ 原值 −0.30 在第一版出图上把整个屋面读成**瓦楞铁皮**（一条 1px 暗线每 7 列、
        拉满 426 行 ⇒ 罗纹太硬）。**−0.18 是"看得出瓦垄、但不抢脊线"的那一档** ——
        南北向脊的屋面本来就长（426 行），纹路一硬就整片压过山墙三角。 */
  const SEAM = -0.18;
  const se = { W: shade(WJ_C.TW, SEAM), E: shade(WJ_C.TE, SEAM),
               T: shade(WJ_C.TILE, SEAM) };
  const F = (a, b, y, col) => wjFill(g, Math.max(ex0, a), Math.min(ex1, b), y, col);
  /* `fOf(x)` = 第 x 列上**山墙三角的上边界**（距檐口的行数）。
     三角在第 t 行（t = yBot − y）的半宽 = half·(1 − t/GA)；
     令 half·(1 − t/GA) = |x − cxi| ⇒ **t = GA·(1 − |x − cxi|/half)**。
     x 越靠外 ⇒ 三角越早收掉（f 越小）⇒ 那条列上的坡面越长。 */
  const fOf = (x) => GA * (1 - Math.abs(x - cxi) / half);
  /* ① 逐行铺底。
     ⚠️ 两侧段在这遍必须铺**纯本色** —— 它们的瓦纹由 ② 竖着画。旧版在这里对侧段
        也套了横纹 ⇒ 两个坡被横竖两遍纹理叠成"网格布"；这遍只铺纯色，不会重犯。
     ⚠️ 山墙那一段**横纹**（照片上屋顶内部就是横条纹）：三角越往上越窄，
        所以横纹自然越来越短 —— 这正是照片上的样子。 */
  for (let y = yTop; y < yBot; y++) {
    const t = yBot - y;
    if (t >= GA) {                                        // 山墙尖以上：纯两坡 + 正脊
      F(ex0, cxi - 2, y, WJ_C.TW);                        // 西坡（迎光）
      F(cxi + 2, ex1, y, WJ_C.TE);                        // 东坡（背光）
      px(g, cxi - 1, y, 3, 1, WJ_C.RIDGE);                // 正脊（屏上那条竖线）
      px(g, cxi - 1, y, 1, 1, WJ_C.RIDGEL);               // 脊顶受光的 1 列
    } else {                                              // 山墙三角那几行
      const hw = R(half * (1 - t / GA));                  // 该行三角的半宽
      const hi = (t % STEP) === 0;
      F(ex0, cxi - hw - 1, y, WJ_C.TW);                   // 坡脚（三角左边）
      F(cxi - hw, cxi + hw, y, hi ? se.T : WJ_C.TILE);    // 山墙面（横纹）
      F(cxi + hw + 1, ex1, y, WJ_C.TE);                   // 坡脚（三角右边）
    }
  }
  /* ② 瓦垄：**平行于正脊**（正脊南北向 ⇒ 屏上是竖线）。
     第 x 列上坡面的行范围 = [yTop, yBot − fOf(x))：山墙三角把下头切掉一块。
     ⚠️ 与 ① 的三角**首尾相接**（三角占 t ≤ f、坡面占 t > f）⇒ 不会两遍叠色。 */
  for (let x = ex0 + 3; x < cxi - 1; x += STEP) {
    const y1 = yBot - R(fOf(x));
    if (y1 - yTop > 2) px(g, x, yTop, 1, y1 - yTop, se.W);
  }
  for (let x = ex1 - 3; x > cxi + 1; x -= STEP) {
    const y1 = yBot - R(fOf(x));
    if (y1 - yTop > 2) px(g, x, yTop, 1, y1 - yTop, se.E);
  }
  /* ③ 两条戗脊（博风）：南檐两角 → 山墙尖。
     ⚠️ 旧版那四条"全汇到顶点"的脊到此为止 —— 南北向正脊的**北端不收敛**
         （那边是北山墙，背对我们、看不见），所以北端只留 ⑤ 那条远檐边。 */
  wjHip(g, ex0, yBot, cxi, YR);
  wjHip(g, ex1, yBot, cxi, YR);
  /* ④ 山墙尖上那一小块暗件（照片峰顶是深色的）—— 只压 3 行，别做成宝顶 */
  px(g, cxi - 1, YR - 3, 3, 3, WJ_C.APEX);
  px(g, cxi - 2, YR, 5, 2, WJ_C.RIDGE);
  /* ⑤ 北端的远檐边：屏上最高那两行就是屋顶**最远**的一条边，压一道暗线收口 */
  px(g, ex0, yTop, ex1 - ex0 + 1, 2, shade(WJ_C.TILE, -0.50));
  /* ⑥ 南檐口：出挑的外沿线 + 压在墙顶上的那道暗投影（照片 583..594） */
  px(g, ex0, yBot - 2, ex1 - ex0 + 1, 2, shade(WJ_C.TILE, -0.55));
  px(g, ex0, yBot, ex1 - ex0 + 1, 1, shade(WJ_C.TILE, -0.72));
}
/* 一段坡面/山墙面的单行。同一个 y 上，瓦纹行在两坡之间是**接得上**的 */
function wjFill(g, x0, x1, y, col) {
  if (x1 < x0) return;
  px(g, x0, y, x1 - x0 + 1, 1, col);
}
/* 一条戗脊：檐角 (x1,y1) → 脊端 (x2,y2)，逐行插值铺 3 列瓦 */
function wjHip(g, x1, y1, x2, y2) {
  const n = Math.abs(y2 - y1), s = y2 > y1 ? 1 : -1;
  for (let i = 0; i <= n; i++) {
    const x = Math.round(x1 + (x2 - x1) * (i / (n || 1)));
    px(g, x - 1, y1 + i * s, 3, 1, WJ_C.RIDGE);
    px(g, x - 1, y1 + i * s, 1, 1, WJ_C.RIDGEL);
  }
}

/* --- 5.18.5 立面构件 ------------------------------------------------------- */
/* 红砖：照片这个尺度上砖缝很浅（直方图上没有暗色簇）
   ⚠️ 第一版是 4 行横缝 + 8 列竖缝、对比 7% —— 放大对照时**整面墙读成"格子布"**，
      而照片上根本看不见砖缝。现在：横缝留（这是砖的层理），竖缝稀疏到每 16 列一个点。
   ⚠️ 竖缝**必须裁到砖带底边**：缝高固定 4 行，而循环只卡了起点 ⇒ 起点落在最后 3 行以内时，
      这道缝会从墙脚探出去，在落地线外面留下若干个砖红色的 1px 点（第三十一轮从 2x 放大图上
      才看出来，五套自动验收全绿 —— 又一个"纯像素"盲区）。`Math.min` 就是那道裁刀。 */
function wjBrick(g, x, y, w, h) {
  px(g, x, y, w, h, WJ_C.BRI);
  for (let yy = y + 3; yy < y + h; yy += 4) px(g, x, yy, w, 1, WJ_C.BRD);
  for (let yy = y, k = 0; yy < y + h; yy += 4, k++)
    for (let xx = x + (k & 1 ? 8 : 0); xx < x + w; xx += 16)
      px(g, xx, yy, 1, Math.min(4, y + h - yy), WJ_C.BRD);
}
/* 灰件（角柱 / 中柱 / 檐口带 / 层间带 / 墙裙）：左上受光、右下背光，服从 SUN。
   ⚠️ 颜色从**实参**进来（BAND / PLIN 与 PIL 不同档），本函数不吃全局 WJ_C。 */
function wjGray(g, x, y, w, h, col) {
  if (h <= 0 || w <= 0) return;
  px(g, x, y, w, h, col);
  px(g, x, y, w, 1, "rgba(255,255,255,0.20)");
  px(g, x, y, 1, h, "rgba(255,255,255,0.14)");
  px(g, x + w - 1, y, 1, h, "rgba(14,18,28,0.20)");
  px(g, x, y + h - 1, w, 1, "rgba(14,18,28,0.26)");
}
/* 一扇窗：**上亮子 + 下两扇**（`_look/_wj_win.png` 放大看：横挺在 37% 高处通到两边，
   竖挺只走横挺以下、落在 53% 处；上亮子反天光所以最亮，下部左扇最深）
   ⚠️ (x,y,w,h) 是**玻璃那块**，白框与凹边都画在它外面 —— 与照片读数一一对应。 */
function wjWin(g, x, y, w, h) {
  /* ① 窗洞凹边：照片 x428..440 / x513..520 各有一圈比墙暗 ~5% 的红（#a73841 / #a1323b）
     ⇒ 窗是**凹进墙里**的。不加这一圈，窗就是"贴在墙上的一张纸"。 */
  px(g, x - 2, y - 2, w + 4, h + 4, WJ_C.WREV);
  /* ② 白框只占 1 列/行。照片里框宽 4px ≈ 0.7 列（x 440..444、440..513 是玻璃），
     第一版画了 1 列全周 + 2 行窗台，出图看是"厚白边"，与照片的窄框不符。 */
  px(g, x - 1, y - 1, w + 2, h + 2, WJ_C.FRM);
  px(g, x + w, y - 1, 1, h + 2, WJ_C.FRMD);                    // 框右背光
  px(g, x - 1, y + h + 1, w + 2, 1, WJ_C.FRMD);                // 框下背光
  const ty = y + Math.max(4, Math.round(h * 0.37));            // 横挺（实测在 37% 高处）
  px(g, x, y, w, ty - y, WJ_C.GLAL);                           // 上亮子
  px(g, x, ty, w, 1, WJ_C.FRM);                                // 横挺通到两边
  px(g, x, ty + 1, w, y + h - ty - 1, WJ_C.GLA);               // 下扇玻璃（右下扇本色）
  /* 中缝竖挺落在 36% 处（照片：左扇 24px / 右扇 33px ⇒ 左窄右宽）。
     ⚠️ 上一版按"53%"画（那是从缩放过的 `_wj_win.png` 上量的），左右扇宽窄是反的。 */
  const mx = x + Math.max(3, Math.round(w * 0.36));
  px(g, mx, ty + 1, 1, y + h - ty - 1, WJ_C.FRM);              // 中缝竖挺
  px(g, x, ty + 1, Math.max(1, mx - x - 1), y + h - ty - 1, WJ_C.GLAD);  // 左扇更深
  /* 下扇越往下越深（照片 x460 列：710..739 #5d708e → 753..778 #48648b） */
  px(g, x, y + h - 3, w, 3, "rgba(20,30,44,0.14)");
  /* ⚠️ 窗台：照片窗下**只有白框自己那一道浅线**（#dfdfe9），没有投影。
     第一版在窗下画了 2 行窗台 + 1 行影、又给亮子加了顶行反光 —— 对照图上
     这两笔让窗读成"贴上去的白相框"，而照片里窗是**沉在墙里**的。两笔都删。 */
}
/* 大门：深蓝双开门 + 门顶横亮子（照片上是**一整层高**的门洞，见文件头表）
   ⚠️ 三段色是照片实测，不是想当然：门洞上沿 #43080a（暗红影）→ 门顶亮子 #040c0f
      （**近黑**，第一版按藏青画是错的）→ 两扇门 #0e2e47（藏青）。 */
function wjDoor(g, G) {
  const d = G.door, w = d.x1 - d.x0 + 1, h = d.bot - d.top + 1;
  const dy = d.top + 3;                                        // 门叶真正起画的行（照片 1165）
  px(g, d.x0 - 2, d.top, w + 4, 3, WJ_C.DOORS);                // 门洞上沿的暗红阴影
  px(g, d.x0 - 2, dy - 1, w + 4, h - 2, WJ_C.DFRM);            // 门洞暗框
  px(g, d.x0 - 1, dy, w + 2, h - 3, "#2b333c");
  /* 亮子只占门高 **1/4**：采样只到 1180~1230（门高 16%~37%）是近黑，再往下 1290 起就是藏青。
     第一版按 41% 画，出图门上是一大块黑，与照片"整扇藏青、只顶上压一道暗"不符。 */
  const ty = dy + Math.max(5, Math.round((d.bot - dy + 1) * 0.25));
  px(g, d.x0, dy, w, ty - dy, WJ_C.DOORD);                     // 横亮子（近黑）
  px(g, d.x0, dy, w, 1, WJ_C.DFRM);
  px(g, d.x0, ty, w, 1, WJ_C.DFRM);                            // 亮子下的横框
  px(g, d.x0, ty + 1, w, d.bot - ty, WJ_C.DOOR);               // 两扇门（藏青）
  const mx = Math.round(d.x0 + w / 2);
  px(g, mx - 1, ty + 1, 2, d.bot - ty, WJ_C.DFRM);             // 中缝
  const gy = ty + Math.round((d.bot - ty) * 0.42);             // 门上玻璃下沿
  px(g, d.x0 + 2, ty + 3, (mx - 1) - (d.x0 + 2), gy - ty - 3, "#1c3f5e");
  px(g, mx + 1, ty + 3, (d.x0 + w - 1) - (mx + 1), gy - ty - 3, "#1c3f5e");
  px(g, d.x0 + 2, gy, w - 4, 1, WJ_C.DFRM);
  px(g, mx - 4, gy + 6, 2, 5, "#c9c4b4");                      // 门把手（一对）
  px(g, mx + 2, gy + 6, 2, 5, "#c9c4b4");
  px(g, d.x0, dy, 1, d.bot - dy + 1, "rgba(255,255,255,0.16)");
  px(g, d.x0 + w - 1, dy, 1, d.bot - dy + 1, "rgba(14,18,28,0.30)");
  px(g, d.x0, d.bot - 2, w, 3, "rgba(14,18,28,0.34)");         // 落地最暗
}

/* --- 5.18.6 立面总装（只在**新画布**上画） ---------------------------------- */
function wjFront(g, G) {
  const x0 = G.x0, x1 = G.x1, w = G.w;
  /* ① 檐下暗带（照片 583..598 —— 屋面板压在墙顶上的那道投影，实测 #25282d **几乎全黑**） */
  px(g, x0, G.under.top, w, G.under.bot - G.under.top + 1, WJ_C.UND);
  /* ② 檐口带（600..619，灰、比壁柱暗一档 —— 檐下背光） */
  wjGray(g, x0 - 1, G.cope.top, w + 2, G.cope.bot - G.cope.top + 1, WJ_C.GRY);
  /* ②' 檐口下缘那道近黑的红边（照片 620..632 实测 #23060a）—— 有无这一笔，
      红墙与灰檐口"贴不贴得住"差别很大 */
  px(g, x0, G.copeb, w, 1, WJ_C.COPEB);
  /* ③ 砖墙底（从砖顶一路到墙脚） */
  wjBrick(g, x0, G.brickT, w, G.gnd.bot - G.brickT + 1);
  /* ④ 红墙里的两根基柱（亮砖 + 两侧暗边） */
  for (const r of G.relief) {
    const rw = r[1] - r[0] + 1;
    if (rw < 3 || r[0] < x0 || r[1] > x1) continue;
    px(g, r[0], G.brickT, rw, G.gnd.bot - G.brickT + 1, WJ_C.BRL);
    px(g, r[0], G.brickT, 1, G.gnd.bot - G.brickT + 1, WJ_C.BRLD);
    px(g, r[1], G.brickT, 1, G.gnd.bot - G.brickT + 1, WJ_C.BRLD);
  }
  /* ⑤ 两条层间灰横带（压在砖与基柱之上，通到两根角柱 —— 照片如此）
     ⚠️ 带子**下沿那道投影必须画**：照片 876~892 里有一簇 #47090a，是灰带在红墙上
        投的影。第一版只有 wjGray 自带的 0.26 暗边，出图看带子是"浮"在墙上的。 */
  for (const b of G.band) {
    wjGray(g, x0, b.top, w, b.bot - b.top + 1, WJ_C.BAND);
    px(g, x0, b.bot + 1, w, 1, WJ_C.BANDSH);
  }
  /* ⑥ 墙裙 + 墙脚最暗那几行 */
  wjGray(g, x0, G.plin.top, w, G.plin.bot - G.plin.top + 1, WJ_C.PLIN);
  px(g, x0, G.gnd.top, w, G.gnd.bot - G.gnd.top + 1, WJ_C.GND);
  /* ⑦ 两根角柱 + 两根中柱（檐口带下沿通到墙裙上沿），底部外扩成基座 */
  const posts = G.corner.concat(G.pil2);
  const pTop = G.cope.bot + 1, pBot = G.plin.top - 1, pph = pBot - pTop + 1;
  for (const p of posts) {
    wjGray(g, p[0], pTop, p[1] - p[0] + 1, pph, WJ_C.PIL);
    px(g, p[1], pTop, 1, pph, WJ_C.PILD);
  }
  for (const p of posts) {                                   // 基座（照片上明显外扩）
    const bx = p[0] - 2, bw = (p[1] - p[0] + 1) + 4, by = G.plin.top - 6;
    /* ⚠️ 基座止于**墙裙下沿**，不许压到 gnd（那道浅散水）：照片上墙脚外是浅色地面，
       第一版基座一路铺到 baseY，把浅带盖成灰的，整个墙脚读成"暗红" */
    px(g, bx, by, bw, G.plin.bot - by + 1, WJ_C.PILB);
    px(g, bx, by, bw, 1, "rgba(255,255,255,0.22)");
    px(g, bx, G.plin.bot, bw, 1, "rgba(14,18,28,0.30)");
  }
  /* ⑧ 窗阵：三列 × 三层；**首层中列让给大门**（照片如此） */
  const ox = (WJ_WIN_W - 1) >> 1;
  for (let f = 0; f < 3; f++)
    for (let i = 0; i < 3; i++) {
      if (f === 2 && i === 1) continue;                      // 首层中间 = 门
      wjWin(g, G.winC[i] - ox, G.winRow[f], WJ_WIN_W, WJ_WIN_H);
    }
  /* ⑨ 雨水管（贴在两根基柱内侧，压在砖上） */
  for (const qx of G.pipes) {
    if (qx < x0 || qx + 2 > x1) continue;
    px(g, qx, pTop, 3, pph, "rgba(14,18,28,0.20)");
    px(g, qx, pTop, 2, pph, WJ_C.PIL);
    px(g, qx, pTop, 1, pph, "#dfe4ea");
  }
  /* ⑩ 大门（最后画，压在首层砖面与两条中柱之间） */
  wjDoor(g, G);
  /* ⑪ 整栋外轮廓 + 接地最深窄带（照 30 段 §3.8） */
  px(g, x0 - 1, G.cope.top, 1, G.baseY - G.cope.top, "#6c6f76");
  px(g, x1, G.cope.top, 1, G.baseY - G.cope.top, "#5c5f66");
  contactBand(g, x0 + 1, x1 - 1, G.baseY - 1, 2, 0.34);
}
/* 台阶：3 级，**画在落地线以外**（照 30 段 §3.7 的处理，本段自己画不搬旧画布） */
function wjSteps(g, G) {
  const cx = Math.round(G.cxr), dw = G.door.x1 - G.door.x0 + 1;
  for (let i = 0; i < 3; i++) {
    const sw = dw + 4 + i * 6, sx = cx - Math.round(sw / 2), sy = G.baseY + i * 3 - 2;
    px(g, sx, sy, sw, 3, shade(WJ_C.STEP, 0.10 - i * 0.11));
    px(g, sx, sy + 3, sw, 1, "rgba(14,18,28,0.26)");
  }
}

/* --- 5.18.7 屋名标牌 --------------------------------------------------------
   30 段 §3.2.9 的牌子挂在 `signRect(sgn, x0, w, eaveY)` = 第 `eaveY−8−h` 行起。
   牌子落在**南端山墙三角**上（第三十三轮起：三角占第 `eaveY−44` ~ `eaveY−1` 行）
   —— 位置、画法、投影偏移全部照 30 段原样，只是脚下的面从平板变成了山墙面。
   ⚠️ 牌子左右两端会压到两个坡面上（见文件头 ⑥），可接受。
   ⚠️ `makeSign(WJ_NAME)` 这一句**必须留着**：`verify.py` 的屋名标牌自检读 `_signCache`，
      少了它这一栋在自检里就"没名字"。 */
function wjSign(g, G) {
  const sgn = makeSign(WJ_NAME);
  const sg  = signRect(sgn, G.x0, G.w, G.eaveY);
  if (!sg) { console.warn("69_wujiao: makeSign 没拿到字形 —— 屋名标牌挂不上"); return; }
  if (sg.y < G.ridgeY + 2)
    console.warn("69_wujiao: 屋名牌第 %d 行顶到正脊（第 %d 行）了", sg.y, G.ridgeY);
  px(g, sg.x + 3, sg.y + 3, sg.w, sg.h, "rgba(14,18,28,0.30)");
  g.drawImage(sgn.c, sg.x, sg.y);
}

/* --- 5.18.8 覆盖重绘入口 ----------------------------------------------------
   ⚠️ 必须在这里、addProp **之前**调（60_assemble.js）—— 重绘的是精灵，
      晚一步 addProp 已经把旧精灵挂进 props 了（gymRestyle/…/qjRestyle 同一规矩）。
   ⚠️ 本函数**不碰共享 RNG、不取任何随机数** ⇒ 建筑序列与全校园散射流一个数不动。
   ⚠️ 与 68 段的分水岭：**不搬旧画布一行**。旧画布的平屋顶板、女儿墙、屋面设备、
      屋面斑点、旧台阶全部作废，新画面从零画（用户要的就是这个）。
      `x0/x1` 是 30 段算出来的原值 ⇒ 立面宽度与占地无关（碰撞盒在 60 段）。
   ⭐ 第三十二轮起：**画布尺寸 `G.H` 与 `b.ay` 都回到 30 段的原值**
      （`roofFull` 那条规矩的附带效果，见文件头）⇒ 这一轮**没有**第三十一轮
      那种"整体上滑 34 行、屋顶压住马路"的副作用。 */
function wjRestyle(b, pal) {
  const c = b.canvas;
  const G = wjGeo(c);
  const nc = mkCanvas(c.width, G.H), ng = nc.getContext("2d");
  /* ① 方向性投影（照 30 段 §3.1，画在立面之前 ⇒ 只有落地线以下留在画面里） */
  const SHX = Math.round(-SUN.x * 26), SHY = Math.round(-SUN.y * 26);
  shadowQuad(ng, G.x0 + 2, G.baseY - WJ_SHADOW_H, G.x1 - 2, G.baseY, SHX, SHY, 0.28, 4);
  /* ② 自设计的南北向正脊双坡顶 */
  wjRoof(ng, G);
  /* ③ 立面 */
  wjFront(ng, G);
  /* ④ 屋名标牌（照 30 段原式挂在新屋面上） */
  wjSign(ng, G);
  /* ⑤ 台阶 */
  wjSteps(ng, G);
  b.canvas = nc;
  b.ay = G.baseY;                    // 同高同锚 ⇒ 与改前逐字节相同（写出来只为把契约写明）
  return b;
}
