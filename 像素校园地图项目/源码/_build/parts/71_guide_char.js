/* =========================================================
   7.1 向导 · 小北 —— 红衣女志愿者
   ---------------------------------------------------------
   **本段不画骨架**：骨架、步态、四向 × 六相位全部走 `50_char.js` 的
   `buildChar(HH, PAL)` —— 它在这一轮加了个配色参数（默认 `A2`，玩家照旧）。
   于是向导与玩家**共用同一套节拍**（同一个 WALK_STRIDE、同一张 GAIT 相位表），
   走在一起不会像两个不同引擎做的游戏。

   为什么必须共用骨架而不是另画一份：像素风最容易露馅的地方就是**比例与描边**。
   同一个人画的 18×30 角色，头身比 4.3、彩色描边 k=0.45、影子偏 +1.5 ——
   另起一份迟早漂移，两个人站一起一眼看出不是一套。

   ⚠️ 三条识别特征，缺一条就会和玩家混淆（3× 档下实测距离约 6 格）：
       ① 红马甲（#c0392b）vs 玩家蓝外套（#3f6ea8）—— 全图唯一的高饱和红
       ② 深棕**长发**（C.longHair 钩子）vs 玩家黑短发
       ③ 白书包 vs 玩家橙书包（#b4552f）
   ========================================================= */

const GUIDE_PAL = {
  /* 皮肤：与玩家同一档，只微微偏暖 —— 同校学生，不该是两种质感 */
  skin:  "#efc5a0", skinD: "#c99a74", skinL: "#ffdfba",
  /* 深棕长发：玩家是近黑的短发（#241d1a），剪影差异主要在侧影那两条垂发 */
  hair:  "#3a2418", hairL: "#54351f", hairD: "#221409",
  /* 志愿者红马甲：全图唯一的饱和红。草坪、沥青、米黄楼群上都跳得出来，
     而且不与任何既有用色撞车（南门拱是 #5c302d 的暗砖红、九教是白瓷砖） */
  coat:  "#c0392b", coatD: "#8c2618", coatL: "#e35b45",
  /* 深灰长裤 + 白鞋 */
  pant:  "#3f4757", pantD: "#282e3a", pantL: "#5a6478",
  shoe:  "#e8e6df", shoeL: "#ffffff",
  /* 白色双肩包：与玩家的橙色包（#b4552f）区分 */
  pack:  "#eceae3", packD: "#c3bfb4", packL: "#ffffff",
  longHair: true                       // ← 开 `50_char.js` 里的长发钩子
};

/* ⚠️ 与 `50_char.js` 的 `makeChar` 同构：头高同为 6px（同一个头身比），
   只是把配色表换了。两者共享 `buildChar`，所以骨架改动会同时作用到两边。 */
const makeGuideChar = buildChar(6, GUIDE_PAL);
const _gchars = Object.create(null);
function guideSprite(dir, step) {
  const k = dir + step;
  if (!_gchars[k]) _gchars[k] = makeGuideChar(dir, step);
  return _gchars[k];
}

/* 锚点与玩家完全一致（`CH_AX / CH_AY`），所以向导和玩家走同一条
   「脚踩在世界坐标 y 上」的规矩 —— 主循环里按 baseY 排序天然正确，
   两人擦身而过时的前后遮挡不用额外处理。 */
const GUIDE_AX = CH_AX, GUIDE_AY = CH_AY;
