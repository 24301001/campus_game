-- =============================================
-- 题库分类整治：题目严格对应分类，空分类清掉
-- =============================================
-- 背景：
--   题库页顶上那排「分类标签」原来有 28 个，其中 6 个一道题都没有
--   （SQL / Java基础 / C++基础 / Python基础 / 前端开发 / 后端开发），
--   看着就是一堆点了没内容的空标签；另外还有题目归错位的情况。
--
-- 做了两件事：
--   1) 归错位的题调回正确分类：
--        - 271-280（面向对象三大特性、接口与抽象类、重载重写、this/super、继承，
--          以及 Lambda、Stream、纯函数、高阶函数等）→「Java基础」
--        - 251-255（5 道 SQL 题，原先挂在「数据库」下）→「SQL」
--   2) 整治后一道题都没有的分类删掉：
--        C++基础、Python基础、前端开发、后端开发、数据库、面向对象、函数式编程
--
-- 结果：分类 28 → 21，空分类 0 个，题目总数 170 不变。
-- 可重复执行。
-- =============================================

UPDATE `problem` SET `category_id` = (SELECT `id` FROM `category` WHERE `name` = 'Java基础')
WHERE `id` BETWEEN 271 AND 280;

UPDATE `problem` SET `category_id` = (SELECT `id` FROM `category` WHERE `name` = 'SQL')
WHERE `id` BETWEEN 251 AND 255;

DELETE FROM `category`
WHERE `id` NOT IN (SELECT DISTINCT `category_id` FROM `problem` WHERE `category_id` IS NOT NULL);


