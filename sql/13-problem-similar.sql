-- 可重复执行：命中唯一键 (problem_id, similar_problem_id) 就更新，不会重复插。

CREATE TABLE IF NOT EXISTS `problem_similar` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `problem_id` bigint NOT NULL COMMENT '题目',
  `similar_problem_id` bigint NOT NULL COMMENT '相似题目',
  `reason` varchar(120) DEFAULT NULL COMMENT '为什么说它像',
  `sort_order` int DEFAULT '0' COMMENT '展示顺序',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_problem_similar` (`problem_id`,`similar_problem_id`)
) ENGINE=InnoDB AUTO_INCREMENT=511 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='题目相似题关联';

