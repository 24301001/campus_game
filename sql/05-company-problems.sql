    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '企业ID',
    `name` VARCHAR(50) NOT NULL COMMENT '企业名称',
    `name_en` VARCHAR(100) DEFAULT NULL COMMENT '英文名',
